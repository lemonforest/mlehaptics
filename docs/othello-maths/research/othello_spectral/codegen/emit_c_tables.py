"""Emit a self-contained C17 header with the encoder's tables.

Generated header contents
-------------------------

    OTHELLO_SPECTRAL_VERSION        — string literal, matches VERSION file
    OTHELLO_SPECTRAL_ENCODING_DIM   — 768
    OTHELLO_SPECTRAL_N_CHANNELS     — 12
    OTHELLO_SPECTRAL_CHANNEL_NAMES  — static const char* [12]
    OTHELLO_SPECTRAL_PROJECTORS     — static const double [10][64][64]
                                        in encoder-channel order, for
                                        the 5 '-' irreps applied to s
                                        and 5 '+' irreps applied to s^2
    OTHELLO_SPECTRAL_L_ORTHO        — static const double [64][64]
    OTHELLO_SPECTRAL_L_DIAG         — static const double [64][64]

Values are formatted with 17 significant digits (the float64 round-
trip precision) so the generated header is bit-identical to the
Python tables when both are parsed as IEEE 754 doubles.

Usage
-----

    cd docs/othello-maths/research
    python -m othello_spectral.codegen.emit_c_tables \\
        --out othello_spectral/c_encoder/include/othello_spectral_tables.h

The header is deliberately generated, not committed with stale
entries (.gitignore entry for the generated file recommended once
the C encoder is built).  Re-run this script after bumping VERSION
or modifying tables.py.
"""

from __future__ import annotations

import argparse
import datetime
import sys
from pathlib import Path

import numpy as np

from ..tables import (
    CHANNEL_NAMES, ENCODING_DIM, N_CHANNELS,
    magn_irreps, occ_irreps, orbit_laplacian_pair, projector,
)
from .. import VERSION


_DOUBLE_FMT = "{:.17e}"


def _format_matrix_double(
    name: str, M: np.ndarray, block_dim: tuple[int, ...],
) -> str:
    """Format a float64 numpy array as a C17 `static const double`
    nested-brace initialiser.  block_dim is the declared shape, e.g.
    (10, 64, 64)."""
    flat = M.astype(np.float64).ravel()
    expected = 1
    for d in block_dim:
        expected *= d
    if flat.size != expected:
        raise ValueError(
            f"shape mismatch: {name} has {flat.size} elements, "
            f"block_dim {block_dim} implies {expected}"
        )
    dim_list = "".join(f"[{d}]" for d in block_dim)
    out = [f"static const double {name}{dim_list} = {{"]
    # Emit one inner-most-dim row per line, 4 values per line for
    # readability at 17 sig figs.
    inner = block_dim[-1]
    total = flat.size
    i = 0
    # For nested array we need balanced braces.  Emit block by block
    # using a recursive helper.
    def emit_block(shape, offset: int, indent: int) -> tuple[list[str], int]:
        lines: list[str] = []
        ind = "    " * indent
        if len(shape) == 1:
            vals = flat[offset: offset + shape[0]]
            chunks = []
            for k in range(0, shape[0], 4):
                chunk = ", ".join(_DOUBLE_FMT.format(v) for v in vals[k:k + 4])
                chunks.append(chunk)
            joined = (",\n" + ind + "    ").join(chunks)
            lines.append(f"{ind}{{ {joined} }}")
            return lines, offset + shape[0]
        lines.append(f"{ind}{{")
        new_off = offset
        for i in range(shape[0]):
            sub_lines, new_off = emit_block(shape[1:], new_off, indent + 1)
            # Append comma except on last
            tail = "," if i < shape[0] - 1 else ""
            joined = "\n".join(sub_lines)
            lines.append(joined + tail)
        lines.append(f"{ind}}}")
        return lines, new_off

    body, _ = emit_block(block_dim, 0, 0)
    out.extend(body)
    out.append("};")
    return "\n".join(out)


def _format_channel_names_c() -> str:
    names = ", ".join(f'"{n}"' for n in CHANNEL_NAMES)
    return (
        f"static const char *const OTHELLO_SPECTRAL_CHANNEL_NAMES"
        f"[{N_CHANNELS}] = {{ {names} }};"
    )


def emit(out_path: Path) -> int:
    # Collect the 10 projectors in encoder-channel order.
    ordered = list(magn_irreps()) + list(occ_irreps())
    assert len(ordered) == 10, ordered
    P_stack = np.stack([projector(lbl) for lbl in ordered], axis=0)
    assert P_stack.shape == (10, 64, 64), P_stack.shape

    L_ortho, L_diag = orbit_laplacian_pair()

    stamp = datetime.datetime.now(datetime.UTC).isoformat()
    header = f"""/* othello_spectral_tables.h — generated by codegen/emit_c_tables.py
 *
 * VERSION: {VERSION}
 * Generated: {stamp}
 *
 * DO NOT EDIT BY HAND.  Regenerate via
 *   python -m othello_spectral.codegen.emit_c_tables \\
 *       --out {out_path.name}
 *
 * Layout matches Python othello_spectral.encoder.encode_768:
 *   dims [  0:320)  5 D4xZ2 '-' irreps applied to magnetisation s
 *   dims [320:640)  5 D4 irreps applied to occupation s^2
 *   dims [640:704)  L_ortho @ s
 *   dims [704:768)  L_diag @ s
 *
 * Bit-identical parity with Python requires the caller to:
 *   - use IEEE 754 float64 accumulators
 *   - apply the matrix operations in the same order (row-major
 *     projector @ sig, cell-major L @ sig)
 *   - downcast to float32 (little-endian) only at the .spectralz
 *     write step, not during encoding math
 */
#ifndef OTHELLO_SPECTRAL_TABLES_H
#define OTHELLO_SPECTRAL_TABLES_H

#include <stddef.h>

#define OTHELLO_SPECTRAL_VERSION       "{VERSION}"
#define OTHELLO_SPECTRAL_ENCODING_DIM  {ENCODING_DIM}
#define OTHELLO_SPECTRAL_N_CHANNELS    {N_CHANNELS}
#define OTHELLO_SPECTRAL_CELLS         64

{_format_channel_names_c()}

/* Projector matrices: [channel][row][col].  channel order matches
 * CHANNEL_NAMES for channels 0..9 (the two fiber channels 10..11
 * are materialised separately as L_ORTHO and L_DIAG). */
{_format_matrix_double('OTHELLO_SPECTRAL_PROJECTORS', P_stack, (10, 64, 64))}

/* Orbit Laplacians for the two fiber channels.  L_ORTHO applied to
 * magnetisation s yields channel 10; L_DIAG yields channel 11. */
{_format_matrix_double('OTHELLO_SPECTRAL_L_ORTHO', L_ortho, (64, 64))}

{_format_matrix_double('OTHELLO_SPECTRAL_L_DIAG', L_diag, (64, 64))}

#endif /* OTHELLO_SPECTRAL_TABLES_H */
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(header, encoding="utf-8")
    size_kb = out_path.stat().st_size / 1024.0
    print(
        f"wrote {out_path}  ({size_kb:.1f} KB, "
        f"version {VERSION}, 10 projectors + L_ortho + L_diag)"
    )
    return 0


def _build_parser():
    default_out = (
        Path(__file__).resolve().parent.parent
        / "c_encoder" / "include" / "othello_spectral_tables.h"
    )
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--out", type=Path, default=default_out,
        help="Output C17 header path.  Default: "
             "othello_spectral/c_encoder/include/othello_spectral_tables.h",
    )
    return p


def main(argv=None):
    args = _build_parser().parse_args(argv)
    return emit(args.out)


if __name__ == "__main__":
    sys.exit(main())
