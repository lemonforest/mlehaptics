def _scan_functions(path: Path) -> list[tuple[str, int, int]]:
    """Crude C function scanner — returns ``(name, lines, asserts)``
    per function defined in `path`. Same algorithm the
    JPL_AUDIT.md audit script uses; pure regex + brace counting.

    Limitations: this isn't a real C parser. It assumes srmech's
    formatting conventions: function definitions are at column 0,
    parameter list opens on the definition line, body brace opens
    on the next line OR same line.

    rc441 (``#T1148``): the scan now runs over :func:`_mask_c_literals` output
    rather than the raw text, so a ``'{'`` / ``'}'`` CHAR LITERAL — or a brace
    inside a string or a comment — can no longer run the brace counter off the
    end of the file. See that function for the measured before/after.
    """
    text = _mask_c_literals(path.read_text(encoding="utf-8"))
    lines = text.split("\n")
    # Track {definition_line_idx: (name, fn_body_open_idx)}
    fn_starts: list[tuple[str, int]] = []

    def_pat = re.compile(
        r"^[a-zA-Z_][a-zA-Z_0-9 \t\*]+[ \t\*]([a-zA-Z_][a-zA-Z_0-9]+)\s*\("
    )
    for i, line in enumerate(lines):
        # Skip declarations (semicolon-terminated)
        if line.rstrip().endswith(";"):
            continue
        m = def_pat.match(line)
        if m is None:
            continue
        # ⚠️ `static const` USED TO BE SKIPPED UNCONDITIONALLY HERE, and that
        # hid every function returning a CONST POINTER from Rules 4 and 5.
        # Measured at rc447: 24 functions across 9 files — cr_walk_json,
        # cr_find_named_chain, genome_find_chrom, json_emit_step, mc_method_spec
        # and 19 more — were scanned by nothing. The skip is meant for const
        # DATA (`static const char *const map_k[4] = {...}`), and an initializer
        # is what distinguishes the two: a definition has a parameter list and
        # no `=` ahead of it.
        #
        # All 24 measured CLEAN on both rules when first revealed, so closing
        # the hole cost zero violations — but it had to close BEFORE the map
        # arm lands, which adds ~45 functions to srmech_compose_run.c. A blind
        # spot is cheapest to fix while it is still empty.
        _is_const_data = (line.lstrip().startswith("static const")
                          and "=" in line.split("(")[0])
        if _is_const_data or line.lstrip().startswith(("typedef", "extern", "#")):
            continue
        # ⚠️ THIS LOOK-AHEAD WAS 10 LINES, AND THAT WAS THE THIRD BLIND SPOT IN
        # THIS SCANNER. A function whose PARAMETER LIST is long pushes its
        # opening brace past the window, and the scanner then never sees the
        # function at all. Measured at rc447: 42 functions across the tree,
        # with braces up to +27 lines past the definition —
        # `srmech_q_zeilberger` at +22, and it is 141 LINES against a 60 cap.
        # 12 Rule-4 and 2 Rule-5 violations had never been audited by anything.
        #
        # 40 covers the measured worst case (+27) with headroom. It is a window,
        # not a parser: the scanner still documents itself as crude, and a
        # fourth shape may exist.
        for look in range(i, min(i + 40, len(lines))):
            if "{" in lines[look] and not lines[look].lstrip().startswith("/*"):
                fn_starts.append((m.group(1), i))
                break

    # For each detected function start, count brace depth to find
    # the closing brace + count asserts in between.
    out: list[tuple[str, int, int]] = []
    for name, start_idx in fn_starts:
        depth = 0
        asserts = 0
        end_idx = start_idx
        # Find first '{'
        body_start = start_idx
        while body_start < len(lines) and "{" not in lines[body_start]:
            body_start += 1
        if body_start >= len(lines):
            continue
        depth = lines[body_start].count("{") - lines[body_start].count("}")
        for j in range(body_start + 1, len(lines)):
            depth += lines[j].count("{") - lines[j].count("}")
            if "assert(" in lines[j]:
                asserts += 1
            if depth == 0:
                end_idx = j
                break
        out.append((name, end_idx - start_idx + 1, asserts))
    return out



