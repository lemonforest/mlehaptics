"""rc291 (#916) — curated introspection docs must SURVIVE a regeneration.

``srmech/amsc/_tool_docs.py`` is generated by ``tools/gen_tool_docs.py``. The
generator has always had a curation-merge layer: hand-written entries live in
``srmech/amsc/_tool_docs_curated.py`` (``CURATED``) and are laid OVER the
docstring-seeded auto-seed, so regeneration cannot clobber them.

That layer was never the problem. It was BYPASSED. Between rc274 and rc290,
twenty genome / plasmid / text explanations were hand-written straight into
the GENERATED file — which is stamped ``DO NOT EDIT`` precisely because a
regeneration destroys anything written there. So every run of the generator
silently replaced four rcs of curation (native-dispatch notes, the rc280
quadratic-fix explanation, the facultative-vs-constitutive chromatin read)
with a one-line docstring seed. It had already happened once and been
reverted by hand.

That makes it LIVE damage rather than latent: the standing public-callable
ripple gate instructs "regenerate ``_tool_docs.py``", and obeying the
instruction degraded the docs. ``tool_schema.py`` then merges ``TOOL_DOCS``
into every ``ToolEntry``, so the loss propagates into ``get_tool_schema()``,
the C tool registry and ``tool_schema_sha256`` — the canonical payload.

rc291 does three things, and this module pins each:

1. migrates the twenty entries into ``CURATED`` where the merge protects
   them (:func:`test_regeneration_is_a_fixed_point`);
2. makes the generator REFUSE to write when it would destroy prose it
   cannot re-derive, instead of doing it silently
   (:func:`test_guard_catches_hand_editing_of_the_generated_file`);
3. stops ``tools/gen_curated_probe.py`` rebuilding the curation SSoT from
   its own hardcoded ``CENTRAL`` list — the same defect, one file over, and
   the more destructive of the two (:func:`test_probe_merge_preserves_*`).

Test 1 is the durable one and it is deliberately written to exercise the
REAL generator rather than the rc291 helper, so it would fail against the
pre-rc291 tree for the true reason (twenty entries diverge) rather than
because a helper is missing.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

PY_ROOT = Path(__file__).resolve().parent.parent
TOOLS = PY_ROOT / "tools"
GENERATED = PY_ROOT / "srmech" / "amsc" / "_tool_docs.py"


def _load_tool(name: str):
    """Import a ``tools/`` script by path (they are not an importable pkg)."""
    for p in (str(PY_ROOT), str(TOOLS)):
        if p not in sys.path:
            sys.path.insert(0, p)
    spec = importlib.util.spec_from_file_location(name, TOOLS / f"{name}.py")
    assert spec is not None and spec.loader is not None, f"cannot load {name}.py"
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def gen():
    return _load_tool("gen_tool_docs")


@pytest.fixture(scope="module")
def built(gen):
    """``build_docs()`` once — it warms every op up and executes examples."""
    return gen.build_docs()


# ── 1. the round-trip ────────────────────────────────────────────────

def test_regeneration_is_a_fixed_point(gen, built):
    """Regenerating must reproduce the COMMITTED file's content exactly.

    This is the whole defect in one assertion. Any entry the generator
    cannot reproduce is an entry a regeneration would overwrite — so if
    this passes, running ``tools/gen_tool_docs.py`` is safe, and if it
    fails, someone has hand-edited the generated file again.

    Compared as parsed DATA, never as text: the committed file has
    historically carried ``\\uXXXX``-escaped prose where the generator
    emits literal UTF-8, and that difference is representation, not
    content. A byte-comparison here would fail for a reason that does not
    matter and mask the reason that does.
    """
    docs, _seed, _curated = built
    from srmech.amsc._tool_docs import TOOL_DOCS as committed

    missing = sorted(set(committed) - set(docs))
    assert not missing, (
        f"{len(missing)} committed tool(s) vanish on regeneration: {missing[:10]}"
    )

    diverged = {
        name: sorted(f for f in committed[name]
                     if docs.get(name, {}).get(f) != committed[name][f])
        for name in committed
    }
    diverged = {k: v for k, v in diverged.items() if v}
    assert not diverged, (
        f"{sum(len(v) for v in diverged.values())} field(s) across "
        f"{len(diverged)} tool(s) would be DESTROYED by regenerating "
        f"_tool_docs.py — they are hand-written into the GENERATED file "
        f"instead of srmech/amsc/_tool_docs_curated.py. Move them to "
        f"CURATED, which the generator merges OVER the auto-seed. "
        f"Offenders: { {k: v for k, v in list(diverged.items())[:6]} }"
    )


def test_the_migrated_genome_explanations_are_curated(built):
    """The specific rc274–rc290 casualties now live in CURATED.

    Named individually so a future wholesale rewrite of the curated file
    fails HERE with the list, rather than silently shrinking the docs.
    """
    from srmech.amsc._tool_docs_curated import CURATED

    casualties = [
        "srmech.amsc.genome.accessible",
        "srmech.amsc.genome.amplify",
        "srmech.amsc.genome.chromatin_of",
        "srmech.amsc.genome.condense",
        "srmech.amsc.genome.copy_number_of",
        "srmech.amsc.genome.decondense",
        "srmech.amsc.genome.genome_catalog",
        "srmech.amsc.genome.genome_census",
        "srmech.amsc.genome.genome_from_graph",
        "srmech.amsc.genome.genome_partition",
        "srmech.amsc.genome.genome_registry",
        "srmech.amsc.genome.integrate",
        "srmech.amsc.genome.mint_strand",
        "srmech.amsc.genome.plasmid",
        "srmech.amsc.plasmid.add_plasmid",
        "srmech.amsc.plasmid.conserved_core",
        "srmech.amsc.plasmid.genome_integrate_plasmids",
        "srmech.amsc.plasmid.plasmid_extract",
        "srmech.amsc.plasmid.section_counts",
        "srmech.amsc.text.glyph_stream",
    ]
    absent = [n for n in casualties if n not in CURATED]
    assert not absent, (
        f"{len(absent)} rc291-migrated explanation(s) fell back out of "
        f"CURATED: {absent}"
    )
    thin = [n for n in casualties
            if len(CURATED[n].get("explanation", "")) < 80]
    assert not thin, (
        f"curated explanation(s) shrank back to auto-seed length — the "
        f"regression this rc closed: {thin}"
    )


# ── 2. the guard ─────────────────────────────────────────────────────

def test_guard_is_silent_on_a_healthy_tree(gen, built):
    """No false positive: the shipped tree has nothing un-rederivable."""
    _docs, seed, curated = built
    committed = gen.load_committed(GENERATED)
    assert gen.unrederivable_fields(committed, seed, curated) == {}


def test_guard_catches_hand_editing_of_the_generated_file(gen, built):
    """Hand-written prose in the GENERATED file is reported, not eaten.

    Synthesises the exact rc274 mistake — an explanation present in the
    committed file, absent from CURATED, and not what the docstring seeds
    — and asserts the generator names it.
    """
    _docs, seed, curated = built
    victim = "srmech.amsc.genome.accessible"
    assert victim in seed, "fixture drifted: op is no longer registered"

    committed = gen.load_committed(GENERATED)
    committed[victim] = dict(committed.get(victim, {}))
    committed[victim]["explanation"] = (
        "Hand-written prose that no docstring can re-derive — four rcs of "
        "native-dispatch and quadratic-fix notes, exactly the shape of the "
        "text rc274-rc290 kept losing."
    )

    # ... and with the victim NOT protected by curation, it must be flagged.
    lost = gen.unrederivable_fields(committed, seed,
                                    {k: v for k, v in curated.items() if k != victim})
    assert victim in lost and "explanation" in lost[victim], (
        "the guard did not notice prose it was about to destroy"
    )

    # The same text, once CURATED, is safe — that is the prescribed fix.
    healed = dict(curated)
    healed[victim] = dict(healed.get(victim, {}))
    healed[victim]["explanation"] = committed[victim]["explanation"]
    assert victim not in gen.unrederivable_fields(committed, seed, healed), (
        "moving the text into CURATED must clear the guard — otherwise the "
        "error message tells the author to do something that does not work"
    )


def test_guard_ignores_unicode_escaping(gen, built):
    """A ``\\uXXXX``-escaped committed file is content-identical, not drift.

    Guards the guard against the false positive that would make authors
    pass ``--accept-seed-drift`` reflexively — which would re-open the
    silent-loss hole this rc closed.
    """
    _docs, seed, curated = built
    committed = gen.load_committed(GENERATED)
    # load_committed parses the module, so escapes are already resolved;
    # assert the resolved text really does contain the non-ASCII that the
    # committed file spells with escapes.
    escaped = [n for n, e in committed.items()
               if any(ord(ch) > 127 for ch in str(e.get("explanation", "")))]
    assert escaped, "fixture drifted: no non-ASCII explanations left to check"
    assert gen.unrederivable_fields(committed, seed, curated) == {}


# ── 3. the probe must merge, not rebuild ─────────────────────────────

def test_probe_merge_preserves_entries_it_did_not_probe():
    """``gen_curated_probe`` must not delete curation outside ``CENTRAL``."""
    probe = _load_tool("gen_curated_probe")
    existing = {
        "srmech.amsc.genome.accessible": {"explanation": "four rcs of curation"},
        "srmech.amsc.cyclic.gcd": {"example": {"input": {"a": "12"}, "output": "6"}},
    }
    probed = {"srmech.amsc.cyclic.gcd": {"example": {"input": {"a": "9"}, "output": "3"}}}

    merged = probe.merge_curated(existing, probed)
    assert "srmech.amsc.genome.accessible" in merged, (
        "the probe dropped a curated entry its CENTRAL list does not mention "
        "— the rc291 #916 defect on the probe side"
    )
    assert merged["srmech.amsc.genome.accessible"]["explanation"] == "four rcs of curation"
    assert merged["srmech.amsc.cyclic.gcd"]["example"]["output"] == "3", (
        "a probed row must still win for the key it probed"
    )


def test_probe_central_does_not_cover_curation():
    """Why the merge is load-bearing: CENTRAL is a strict subset.

    If this ever inverts, the wholesale rewrite would look harmless in
    testing and still be wrong — so pin the asymmetry that makes the
    merge necessary.
    """
    probe = _load_tool("gen_curated_probe")
    from srmech.amsc._tool_docs_curated import CURATED

    central = {name for name, _args, _expl in probe.CENTRAL}
    uncovered = set(CURATED) - central
    assert uncovered, (
        "CENTRAL now covers all curation; re-examine whether the probe's "
        "merge is still the right shape"
    )
