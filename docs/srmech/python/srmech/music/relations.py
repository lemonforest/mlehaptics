# §3  tempers_out  —  Class I ∘ Class N
# ══════════════════════════════════════════════════════════════════════
def _patent_val(prime: int, edo: int) -> int:
    """Steps of ``edo``-EDO nearest to the prime — by EXACT integer compare.

    ``round(edo * log2(prime))`` is the textbook patent val, but a logarithm is
    the one thing this package will not carry. The identity that removes it:

        ``k == round(edo·log2 p)``  ⟺  ``2**(2k-1) <= p**(2·edo) < 2**(2k+1)``

    which is a comparison between two exact integers. No log, no float, no
    tolerance — the val is DECIDED, not estimated.
    """
    target = prime ** (2 * edo)
    m = target.bit_length() - 1  # 2**m <= target < 2**(m+1)
    for k in ((m - 1) // 2, m // 2, (m + 1) // 2, m // 2 + 1):
        if k < 0:
            continue
        if (1 << (2 * k - 1) if 2 * k - 1 >= 0 else 0) <= target < (
                1 << (2 * k + 1)):
            return k
    raise ValueError(  # pragma: no cover - unreachable by the bracket above
        f"no patent-val step found for prime {prime} in {edo}-EDO")


def tempers_out(comma: _RatioIn, edo: int,
                den: _RatioIn = None) -> Dict[str, object]:
    """Does ``edo``-tone equal temperament **temper out** this comma?

    A temperament tempers out a comma exactly when the comma maps to the
    UNISON under that temperament's val — i.e. when the comma's monzo lies in
    the kernel of the map ``p ↦ round(edo·log2 p)``. This op decides that by
    exact integer comparison (see :func:`_patent_val`); nothing is rounded and
    no tolerance is consulted.

    This is the op that explains the keyboard. 12-EDO tempers out the
    **syntonic** comma ``81/80`` — which is what makes it a meantone
    temperament and why a piano has one key for both ``D#`` and ``Eb`` — and it
    tempers out the **Pythagorean** comma ``531441/524288``, which is what
    closes the circle of fifths that §3.46.2 measures as structurally open in
    the frequency lane. 5-EDO tempers out neither.

    :param comma: the comma as an exact ``[num, den]`` pair / ``Q`` / int, or
        a bare numerator when ``den`` is given.
    :param edo: the equal division of the octave, ``>= 1``.
    :param den: the denominator when ``comma`` was a bare int.
    :returns: ``{'tempers_out', 'steps', 'comma', 'edo', 'val', 'monzo'}``
        where ``steps`` is the signed number of EDO steps the comma maps to
        (zero exactly when it is tempered out) and ``val`` is the patent val
        restricted to the primes the comma actually uses.

    Exact integer; numpy-free; no ``abs()``.
    """
    if isinstance(edo, bool) or not isinstance(edo, int):
        raise TypeError(f"edo must be int, got {type(edo).__name__}")
    if edo < 1:
        raise ValueError(f"edo must be >= 1; got {edo}")
    if den is None:
        limits = just_limit(comma)
    else:
        limits = just_limit(comma, den)

    monzo = limits["monzo"]
    val: Dict[str, int] = {}
    steps = 0
    for (p_str, exponent) in monzo.items():
        k = _patent_val(int(p_str), edo)
        val[p_str] = k
        steps += exponent * k
    return {
        "tempers_out": (steps == 0),
        "steps": steps,
        "comma": limits["ratio"],
        "edo": edo,
        "val": val,
        "monzo": monzo,
    }


