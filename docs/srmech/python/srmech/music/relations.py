# ══════════════════════════════════════════════════════════════════════
# Wire coercion — bare int or exact [num, den] pair, matching the
# sibling acoustic ops. float is REFUSED, loudly, on purpose.
# ══════════════════════════════════════════════════════════════════════
def _as_ratio(value: _RatioIn, what: str) -> Tuple[int, int]:
    """Coerce a wire ratio to an exact ``(num, den)`` pair of ints."""
    if isinstance(value, bool):
        raise TypeError(f"{what} must be an exact ratio, not bool")
    if isinstance(value, int):
        return (value, 1)
    if isinstance(value, Q):
        return (int(value.numerator), int(value.denominator))
    if isinstance(value, float):
        raise TypeError(
            f"{what} must be EXACT — got float {value!r}. A float has already "
            "lost the distinction this module exists to keep: 81/80 and 1/1 "
            "are different intervals, and a float that rounds one to the "
            "other has erased a comma. Pass an int, an exact [num, den] "
            "pair, or a Q.")
    if isinstance(value, Sequence) and len(value) == 2:
        num, den = value
        if isinstance(num, bool) or isinstance(den, bool):
            raise TypeError(f"{what} pair must be ints, not bool")
        if not isinstance(num, int) or not isinstance(den, int):
            raise TypeError(
                f"{what} must be an exact [num, den] pair of ints; got "
                f"[{type(num).__name__}, {type(den).__name__}]")
        return (num, den)
    raise TypeError(
        f"{what} must be an int, an exact [num, den] pair, or a Q; got "
        f"{type(value).__name__}")


def _sign_split(n: int) -> Tuple[int, int]:
    """Class-K pin-slot: split ``n`` into (orientation, magnitude).

    The pin-slot IS the phase boundary at zero; the orientation it returns is
    the Class-C datum that a later step re-applies. This is the module's ONLY
    sign primitive — ``abs()`` never appears, because ``abs()`` would DISCARD
    the orientation instead of naming it.
    """
    if n < 0:
        return (-1, -n)
    if n > 0:
        return (1, n)
    return (0, 0)


def _reduce(num: int, den: int, what: str) -> Tuple[int, int]:
    """Reduce a positive ratio to lowest terms through the Class-I gcd."""
    if den == 0:
        raise ValueError(f"{what} has zero denominator")
    orient_n, mag_n = _sign_split(num)
    orient_d, mag_d = _sign_split(den)
    if orient_n <= 0 or orient_d <= 0:
        raise ValueError(
            f"{what} must be a POSITIVE ratio; got {num}/{den}. A frequency "
            "ratio is a positive rational — the sign lane in this module is "
            "the monzo EXPONENT's, never the ratio's.")
    g = gcd(mag_n, mag_d)  # Class I
    return (mag_n // g, mag_d // g)


