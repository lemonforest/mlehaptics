"""``srmech.music.relations`` — the RELATIONAL music surface (rc424, `#T1113`).

The sibling ``_spectra`` / ``_instruments`` modules answer questions about a
single sounding object: *what partials does this bell have, and do they share a
period?* This module answers the other kind of question entirely — **how two
pitches stand to one another**, and how a whole collection of them stands to
itself. Nothing here is acoustics; nothing here reads a spectrum.

WHY IT IS A SEPARATE MODULE
===========================
``srmech.music``'s ``__init__`` docstring has always insisted that "harmonic" in
the acoustic sense and "harmonic" in the chirality-order sense never meet. That
discipline generalises: **the acoustic lane and the relational lane are also
different questions**, and mixing them is how a spectrum op ends up being asked
for a scale degree. So the relational ops live here, and the seam is explicit.

THE TWO LANES, AND WHY BOTH ARE EXACT
=====================================
Everything is exact ℚ or exact ℤ. There is no ``float`` anywhere, no stdlib
``math`` / ``fractions`` / ``decimal``, no numpy, and no ``abs()`` — sign is
handled as a **Class-K pin-slot phase boundary** with **Class-C** re-application
per ``[[feedback_sign_handling_is_class_k_pin_slot_not_alu_abs]]``.

**Lane 1 — the FREQUENCY lane (ℚ⁺ under multiplication).** ``just_limit`` and
``comma_of_chain`` live here. A just interval is a rational; its *p-limit* is
the largest prime in its factorisation, which makes p-limit tuning exactly the
multiplicative subgroup of ℚ⁺ generated by the primes ≤ p (Wright, *Mathematics
and Music*, AMS 2009, §9). Class J decides it; Class I reduces first; Class N
carries it.

**Lane 2 — the MODULAR lane (ℤ/12 under addition).** ``interval_vector`` /
``normal_order`` / ``prime_form`` live here. Class I supplies the group action,
Class E supplies the canonical-representative selection.

⚠️ **THE TWO LANES DO NOT AGREE, AND THAT IS THE POINT** (notebook §3.46.2).
The frequency lane never closes — ``(3/2)**n = 2**m`` has no solution for
``n > 0``, because the prime supports ``{3}`` and ``{2}`` are disjoint (Class J
deciding a question Class I cannot even pose). The modular lane always closes,
because a generator coprime to the modulus generates the whole cycle. The exact
non-vanishing residue between them IS a comma, and ``comma_of_chain`` DERIVES it
rather than looking it up.

⚠️ **CLASS N IS THE WRONG TOOL FOR EVERY OP IN THIS MODULE, AND SPECTACULARLY
SO** (`#T1014`). ``best_rational`` does not *approximate* a musical interval —
it **replaces** it with a different one you can hear. Measured on the shipped
op: the syntonic comma ``81/80`` at ``max_denominator=10`` comes back as
``1/1`` — the comma is **erased to a unison**, which is precisely the thing a
comma is defined by not being. And 12-EDO's irrational major third comes back
as an exact ``5/4`` at ``max_denominator=10``, silently converting an
inharmonic spectrum into a just one. Every op here therefore carries the exact
value and never an anchor; ``just_limit``'s worked example ships the divergence
side by side so it is demonstrated rather than merely warned about.

WHAT IS DELIBERATELY NOT HERE
=============================
``interval_invert`` / ``pitch_class_transpose`` / ``pitch_class_invert`` were
costed and **REJECTED**: each is a single ``cyclic_mod_add`` call carrying no
decision, so registering one would add registry surface for zero capability.
The ℤ/7 note-alphabet walk of §3.46.2 (fifth ``+4``, fourth ``+3``, ``4+3=7``
the conserved octave) ships as a worked example and an ``[[alias]]`` entry, not
as an op, for the same reason. Psychoacoustics, timbre and fingerboard
GEOMETRY are out of scope — the last by the CAD-scope ban (§3.46.3 says so in
those words).
"""

