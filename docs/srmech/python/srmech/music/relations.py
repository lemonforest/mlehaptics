# §1  just_limit  —  Class J ∘ Class I ∘ Class N
# ══════════════════════════════════════════════════════════════════════
def just_limit(num: _RatioIn, den: _RatioIn = 1) -> Dict[str, object]:
    """The **p-limit**, prime support and **monzo** of a just interval.

    p-limit tuning is exactly the multiplicative subgroup of ℚ⁺ generated by
    the primes ≤ p, so "what limit is this interval?" is literally "what is the
    largest prime in its factorisation?" — a **Class J** question, asked of a
    ratio that **Class I** has reduced first and that **Class N** carries
    exactly.

    The **monzo** is the exponent vector of that factorisation: ``3/2`` is
    ``{2: -1, 3: 1}``, i.e. ``2**-1 * 3**1``. It is the interval's coordinates
    in the free abelian group on the primes, which is what makes comma
    arithmetic (``comma_of_chain``) and temperament kernels (``tempers_out``)
    exact integer linear algebra rather than approximation.

    The **odd limit** drops the prime 2, because octave-equivalence is assumed
    in most tuning literature: ``2/1`` is 2-limit but 1-odd-limit.

    :param num: the numerator, or the whole ratio as an exact ``[num, den]``
        pair / ``Q``. float is REFUSED.
    :param den: the denominator when ``num`` was a bare int. Default ``1``.
    :returns: ``{'ratio', 'num', 'den', 'primes', 'limit', 'odd_limit',
        'monzo', 'class_n_anchor_at_10'}``.

    Exact-ℚ; numpy-free; no ``abs()``.
    """
    if den == 1 and not isinstance(num, int):
        num, den = _as_ratio(num, "interval")
    else:
        num, _ = _as_ratio(num, "numerator")
        den, _ = _as_ratio(den, "denominator")
    num, den = _reduce(num, den, "interval")

    fn = factor(num)  # Class J
    fd = factor(den)  # Class J
    monzo: Dict[int, int] = {}
    for (p, e) in fn:
        monzo[p] = monzo.get(p, 0) + e
    for (p, e) in fd:
        monzo[p] = monzo.get(p, 0) - e
    primes = sorted(p for p in monzo if monzo[p] != 0)
    odd = [p for p in primes if p != 2]
    return {
        "ratio": f"{num}/{den}",
        "num": num,
        "den": den,
        "primes": tuple(primes),
        "limit": (max(primes) if primes else 1),
        "odd_limit": (max(odd) if odd else 1),
        "monzo": {str(p): monzo[p] for p in sorted(monzo) if monzo[p] != 0},
    }


# ══════════════════════════════════════════════════════════════════════
# §2  comma_of_chain  —  Class N ∘ Class J   (DERIVED, never a table)
# ══════════════════════════════════════════════════════════════════════
def _period_reduce(num: int, den: int,
                   p_num: int, p_den: int) -> Tuple[int, int, int]:
    """Fold ``num/den`` into ``[1, period)`` by integer powers of the period.

    Pure exact-ℤ cross-multiplication — no logarithm, no float, no ``abs()``.
    Returns ``(num, den, k)`` where ``k`` is the SIGNED number of periods
    removed (Class-C: the orientation of the reduction is data, not noise).
    """
    k = 0
    # while num/den >= p_num/p_den  <=>  num*p_den >= den*p_num
    while num * p_den >= den * p_num:
        num, den = num * p_den, den * p_num
        num, den = _reduce(num, den, "residue")
        k += 1
    # while num/den < 1
    while num < den:
        num, den = num * p_num, den * p_den
        num, den = _reduce(num, den, "residue")
        k -= 1
    return (num, den, k)


def comma_of_chain(gen: _RatioIn, n: int,
                   period: _RatioIn = 2) -> Dict[str, object]:
    """**DERIVE** the comma of an ``n``-step generator chain — never look it up.

    Stack the generator ``n`` times and fold the result back into ``[1,
    period)`` by whole periods. What is left over is the **comma**: the exact
    rational by which the chain FAILS to close. A table of five named constants
    would earn nothing; deriving the residue from the chain is the capability,
    and it answers for generators and periods no table lists.

    The two most-cited commas both fall out of this one op:

    * ``comma_of_chain((3, 2), 12, (2, 1))`` → ``531441/524288``, the
      **Pythagorean comma** — twelve just fifths against seven octaves.
    * ``comma_of_chain((3, 2), 4, (5, 1))`` → ``81/80``, the **syntonic
      comma** — four just fifths against a just major third two octaves up.

    ⚠️ **The residue is structural, not an error term.** ``(3/2)**n == 2**m``
    has no solution for ``n > 0`` by unique factorisation: the prime supports
    ``{3}`` and ``{2}`` are disjoint. So the chain does not *nearly* close and
    it does not close *badly* — it **cannot** close, and the comma is the exact
    measure of that impossibility (notebook §3.46.2; Class J deciding a
    question Class I cannot pose).

    :param gen: the generator ratio, ``> 1``. Exact ``[num, den]`` / ``Q`` /
        int; float REFUSED.
    :param n: how many generators to stack. ``n >= 0``.
    :param period: the equivalence interval, ``> 1``. Default ``2`` (the
        octave).
    :returns: ``{'comma', 'num', 'den', 'vanishes', 'periods_removed',
        'limit', 'monzo', 'factorisation_unavailable', 'gen', 'n', 'period'}``.
        ``limit`` and ``monzo`` are ``None``, with a reason in
        ``factorisation_unavailable``, when the residue exceeds the Class-J
        2**64 parity surface — which a long chain reaches quickly (41 fifths
        already carries a 20-digit numerator). The comma itself stays exact
        there; only the prime-support enrichment is withheld.

    Exact-ℚ; numpy-free; no ``abs()``.
    """
    if isinstance(n, bool) or not isinstance(n, int):
        raise TypeError(f"n must be int, got {type(n).__name__}")
    if n < 0:
        raise ValueError(
            f"n must be non-negative; got {n}. A negative chain is the "
            "reciprocal generator's positive chain — invert `gen` instead, so "
            "the read direction stays explicit (Class C).")
    g_num, g_den = _reduce(*_as_ratio(gen, "gen"), "gen")
    p_num, p_den = _reduce(*_as_ratio(period, "period"), "period")
    if g_num * 1 <= g_den * 1:
        raise ValueError(
            f"gen must exceed 1; got {g_num}/{g_den}")
    if p_num <= p_den:
        raise ValueError(
            f"period must exceed 1; got {p_num}/{p_den}")

    num, den = 1, 1
    for _ in range(n):
        num, den = _reduce(num * g_num, den * g_den, "chain")
    num, den, k = _period_reduce(num, den, p_num, p_den)

    # The COMMA is exact at every n — it is only the Class-J enrichment
    # (limit / monzo) that is bounded, because `factor` binds the fixed-width
    # `srmech_factor` and refuses an operand beyond 2**64 - 1. A long chain
    # reaches that quickly: 41 fifths already carries a 20-digit numerator.
    # So the enrichment is reported ABSENT rather than allowed to destroy a
    # correct comma — the same shape as commensurability_verdict's optional
    # period_multiplier, and for the same reason.
    if num > _CLASS_J_PARITY_MAX or den > _CLASS_J_PARITY_MAX:
        limit = None
        monzo = None
        unavailable = (
            f"the residue {num}/{den} exceeds the Class-J parity surface of "
            f"2**64 - 1, so its prime support is not factorable on this "
            f"surface. The COMMA ITSELF is exact and unaffected — only the "
            f"limit and monzo are withheld. Call just_limit() directly to get "
            f"the refusal as a raise.")
    else:
        limits = just_limit((num, den))
        limit = limits["limit"]
        monzo = limits["monzo"]
        unavailable = None

    return {
        "comma": f"{num}/{den}",
        "num": num,
        "den": den,
        "vanishes": (num == den),
        "periods_removed": k,
        "limit": limit,
        "monzo": monzo,
        "factorisation_unavailable": unavailable,
        "gen": f"{g_num}/{g_den}",
        "n": n,
        "period": f"{p_num}/{p_den}",
    }


