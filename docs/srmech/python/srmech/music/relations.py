# §4  the ℤ/12 modular lane  —  Class I ∘ Class E
# ══════════════════════════════════════════════════════════════════════
def _as_pcs(pcs: Sequence[int]) -> Tuple[int, ...]:
    """Coerce to a sorted tuple of DISTINCT pitch classes in ℤ/12."""
    if isinstance(pcs, (str, bytes)) or not isinstance(pcs, Sequence):
        raise TypeError(
            f"pcs must be a sequence of ints; got {type(pcs).__name__}")
    out = set()
    for x in pcs:
        if isinstance(x, bool) or not isinstance(x, int):
            raise TypeError(
                f"pitch classes must be ints; got {type(x).__name__}")
        out.add(cyclic_mod_add(x % _EDO12, 0, _EDO12))  # Class I
    if not out:
        raise ValueError("pcs must be non-empty")
    return tuple(sorted(out))


def _interval_class(a: int, b: int) -> int:
    """The interval CLASS between two pitch classes — Class I then Class K.

    Class I gives the directed distance ``(b - a) mod 12`` through the shipped
    modular add. Class K then folds it at the **tritone**, which is the phase
    boundary: 6 is the unique self-inverse interval in ℤ/12 (12 is even, so the
    octave CAN be bisected — in ℤ/7 no step is self-inverse because 7 is odd,
    §3.46.2's ``7/2 = 3.5``). The fold is a pin-slot decision at that boundary,
    NOT an ``abs()``.
    """
    d = cyclic_mod_add(b, _EDO12 - a, _EDO12)  # Class I
    return d if d <= _EDO12 // 2 else _EDO12 - d  # Class K pin-slot at 6


def interval_vector(pcs: Sequence[int]) -> Tuple[int, ...]:
    """The **interval-class vector**: how a pitch-class set relates to ITSELF.

    Entry ``i`` counts the unordered pairs separated by interval class ``i+1``,
    for ``i`` in ``0..5``. The major triad ``[0, 4, 7]`` gives ``(0, 0, 1, 1,
    1, 0)`` — one minor third, one major third, one fourth — and the minor
    triad ``[0, 3, 7]`` gives the SAME vector, which is the first hint that
    this invariant is coarse.

    ⚠️ **IT IS NOT A COMPLETE INVARIANT, AND THE LOSS HAS A NAME.** Measured
    over all set classes of cardinality 2..10: **23 interval vectors are shared
    by more than one set class**. Those are the **Z-related** pairs — genuinely
    different objects with identical interval content, e.g. ``[0,1,3,7]`` and
    ``[0,1,4,6]`` both giving ``(1,1,1,1,1,1)``. So this op answers "what
    intervals does this set contain?" and NOT "which set class is this?". For
    the latter, use :func:`prime_form`, and note that even *it* cannot separate
    a Z-pair by interval content — only by the set class itself.

    :param pcs: pitch classes; reduced mod 12 and de-duplicated.
    :returns: a 6-tuple of counts.

    Exact integer; numpy-free; no ``abs()``.
    """
    s = _as_pcs(pcs)
    v = [0] * (_EDO12 // 2)
    for i in range(len(s)):
        for j in range(i + 1, len(s)):
            v[_interval_class(s[i], s[j]) - 1] += 1
    return tuple(v)


def _rotations(s: Tuple[int, ...]):
    n = len(s)
    return [tuple(s[(i + k) % n] for k in range(n)) for i in range(n)]


def _spans(rot: Tuple[int, ...]) -> Tuple[int, ...]:
    a0 = rot[0]
    return tuple(cyclic_mod_add(x, _EDO12 - a0, _EDO12) for x in rot[1:])


def _check_convention(convention: str) -> str:
    if convention not in CONVENTIONS:
        raise ValueError(
            f"convention must be one of {CONVENTIONS!r}; got "
            f"{convention!r}. There is NO DEFAULT on purpose: Forte (1973) "
            "and Rahn (1980) disagree on 6 of the 208 set classes, so an "
            "unnamed convention would silently pick a side in a live "
            "scholarly disagreement and be wrong for whichever community it "
            "did not pick.")
    return convention


def normal_order(pcs: Sequence[int], convention: str) -> Tuple[int, ...]:
    """The **normal order** of a pitch-class set — convention REQUIRED.

    The most compact rotation of the set. Both conventions first minimise the
    outer span; they break the tie differently, and the difference is the whole
    reason ``convention`` has no default:

    * ``"forte"`` — Forte (1973) packs **from the left**: after the span, compare
      the first interval, then the second, and so on outward.
    * ``"rahn"`` — Rahn (1980) packs **from the right**: after the span, compare
      the interval to the second-to-last, then the third-to-last, working
      inward from the end.

    :param pcs: pitch classes; reduced mod 12 and de-duplicated.
    :param convention: ``"forte"`` or ``"rahn"``. **Required.**
    :returns: the pitch classes in normal order (NOT transposed to 0 — see
        :func:`prime_form` for that).

    Exact integer; numpy-free; no ``abs()``.
    """
    _check_convention(convention)
    s = _as_pcs(pcs)
    best = None
    for rot in _rotations(s):
        d = _spans(rot)
        if not d:
            key: Tuple[int, ...] = ()
        elif convention == RAHN:
            key = (d[-1],) + tuple(reversed(d[:-1]))
        else:
            key = (d[-1],) + tuple(d[:-1])
        if best is None or key < best[0] or (key == best[0] and rot < best[1]):
            best = (key, rot)
    return best[1]


def _invert(s: Tuple[int, ...]) -> Tuple[int, ...]:
    """Inversion about 0 — Class I, through the shipped modular add."""
    return tuple(sorted({cyclic_mod_add(0, (_EDO12 - x) % _EDO12, _EDO12)
                         for x in s}))


def prime_form(pcs: Sequence[int], convention: str) -> Tuple[int, ...]:
    """The **prime form** of a pitch-class set — convention REQUIRED.

    The canonical representative of the set class under Tn/TnI: take the normal
    order of the set and of its inversion, transpose each to start at 0, and
    keep the smaller. This is the **Class E** half of the op — a catalog
    selection over the **Class I** group orbit.

    ⚠️ **THE CONVENTION IS NOT COSMETIC — IT IS A LIVE SCHOLARLY DISAGREEMENT,
    AND WE MEASURED IT.** Enumerating all set classes of cardinality 2..10
    (220 of them; 208 counting the standard 3..9 table) and comparing the two
    algorithms row by row, **exactly 6 set classes disagree**:

    ==========  =====================  =====================
    set class   ``"forte"``            ``"rahn"``
    ==========  =====================  =====================
    5-20        ``(0,1,3,7,8)``        ``(0,1,5,6,8)``
    6-Z29       ``(0,1,3,6,8,9)``      ``(0,2,3,6,7,9)``
    6-31        ``(0,1,3,5,8,9)``      ``(0,1,4,5,7,9)``
    7-Z18       ``(0,1,2,3,5,8,9)``    ``(0,1,4,5,6,7,9)``
    7-20        ``(0,1,2,4,7,8,9)``    ``(0,1,2,5,6,7,9)``
    8-26        ``(0,1,2,4,5,7,9,10)`` ``(0,1,3,4,5,7,8,10)``
    ==========  =====================  =====================

    Note **7-Z18**. The figure most often quoted is *five*, following Straus's
    *Introduction to Post-Tonal Theory*, which omits it. Six is what the
    algorithms actually do, and it is what independent open set-class tables
    list. Our value is COMPUTED, not copied, and the test suite pins all six.

    An unnamed ``prime_form`` would silently answer as one community and be
    wrong for the other on these six. Hence: no default, ever.

    :param pcs: pitch classes; reduced mod 12 and de-duplicated.
    :param convention: ``"forte"`` or ``"rahn"``. **Required.**
    :returns: the prime form, starting at 0.

    Exact integer; numpy-free; no ``abs()``.
    """
    _check_convention(convention)
    s = _as_pcs(pcs)
    cands = []
    for t in (s, _invert(s)):
        no = normal_order(t, convention)
        cands.append(tuple(cyclic_mod_add(x, _EDO12 - no[0], _EDO12)
                           for x in no))
    return min(cands)
