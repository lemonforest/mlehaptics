""".mcpb (Claude Desktop MCP Bundle) emitter — built ENTIRELY from
srmech introspection. No hand-authored manifest, no hardcoded version /
tool-list / interpreter path.

Spec: anthropics/mcpb MANIFEST.md (server.type ``uv | python | node |
binary``; a ``.mcpb`` IS a ZIP archive whose ROOT carries
``manifest.json``). The ``uv`` server.type is the spec's own recommended
answer for a package that "cannot portably bundle compiled dependencies":
at install time the host runs ``uv`` against the bundled
``pyproject.toml`` and resolves ``srmech`` from PyPI, pulling the correct
platform wheel (with the compiled ``libsrmech.{so,dll,dylib}`` inside) —
nothing native is bundled in the ``.mcpb`` itself. A ``python`` fallback
(``user_config``-gated interpreter path) is kept for hosts without uv.

Framework reading: Class F (render srmech's own shape to the Claude
Desktop substrate-class) ∘ Class E (catalog enumeration of the advertised
tool surface) ∘ Class A (content-addressing the tool_schema via
``sha256_bytes`` for the MPR attestation block) ∘ Class H
(self-introspection — the package describing its own callable shape).
"""

from __future__ import annotations

import datetime
import json
import zipfile
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional


# ──────────────────────────────────────────────────────────────────────
# Module constants
# ──────────────────────────────────────────────────────────────────────

_MANIFEST_VERSION = "0.4"
"""The ``.mcpb`` manifest SCHEMA revision (the spec example value) — NOT
srmech's own version. Deliberately decoupled: ``manifest_version`` tracks
the anthropics/mcpb format; ``version`` (below) tracks ``srmech.__version__``."""

_DEFAULT_NAME = "srmech"
_SERVER_ENTRY_POINT = "server/main.py"

# The bundled entry-point shim. Defaults to stdio transport (``main([])``
# ignores process argv) — exactly what Claude Desktop spawns.
_SERVER_SHIM = (
    "# Generated by `srmech mcp emit-mcpb`.\n"
    "from srmech.mcp._cli import main\n"
    "raise SystemExit(main([]))\n"
)


# ──────────────────────────────────────────────────────────────────────
# Private helpers
# ──────────────────────────────────────────────────────────────────────


def _utc_now_iso() -> str:
    """MPR ``retrieved_at``-style UTC stamp (``...Z``, second-resolution).

    Uses ``datetime.timezone.utc`` (3.10-safe; ``datetime.UTC`` is 3.11+,
    but ``requires-python`` is ``>=3.10``)."""
    return (
        datetime.datetime.now(datetime.timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def _advertised_tool_defs(
    *, name_filter: Optional[Callable[[str], bool]] = None
) -> List[Dict[str, Any]]:
    """The SSoT ADVERTISED tool surface (honours ``mcp_callable`` +
    ``--filter``) as a concrete list."""
    from ._tools import tool_entries_to_mcp_defs

    return list(tool_entries_to_mcp_defs(name_filter=name_filter))


def _owned_tool_schema():
    """The live tool schema RESTRICTED to rows srmech itself owns.

    v0.9.0rc410 (`#T1085`) — the attestation block may only speak for what
    srmech OWNS. ``get_tool_schema()`` deliberately publishes
    ``srmech_tools + profile_tools`` (see its docstring), so on a host with any
    profile active the unfiltered schema carries third-party rows. An
    attestation computed over those rows claims *someone else's* tool surface
    under srmech's own ``parser_version`` stamp — and, decisively, it is **not
    re-verifiable**: a consumer re-running the hash against a plain ``pip
    install srmech`` can never reproduce it, because the profile is not part of
    srmech. Per the MPM discipline an attestation that cannot be re-verified is
    broken, so the filter is a correctness requirement, not a preference.

    NOTE this is a NO-OP on a clean tree — the owner census there has the single
    key ``'srmech'``, so owned == total and the emitted bytes are identical.
    That is proven, not assumed, by
    ``tests/test_owner_axis_rc410.py::test_the_owner_filter_is_a_byte_level_noop_on_a_clean_registry``.
    """
    from dataclasses import replace

    from ..introspect.tool_schema import RESERVED_OWNERS, get_tool_schema

    schema = get_tool_schema()
    return replace(
        schema,
        tools=tuple(t for t in schema.tools if t.owner in RESERVED_OWNERS),
    )


def _tool_schema_hash() -> str:
    """Content-address srmech's OWN declared tool schema (stable, sorted)
    via :func:`srmech.amsc.format.sha256_bytes` — the AMSC attestation
    hash. Routes native dispatch; no new ``hashlib.sha256`` call.

    Hashes :func:`_owned_tool_schema`, NOT the unfiltered view — see there for
    why. Byte-identical to the unfiltered pre-image whenever no profile is
    active, which is every srmech CI run."""
    from ..amsc.format import sha256_bytes

    payload = json.dumps(
        _owned_tool_schema().to_jsonable(), sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    return sha256_bytes(payload)  # 64 lowercase hex


def _server_block(server_type: str) -> Dict[str, Any]:
    """The ``server`` object for the chosen ``server_type``.

    ``uv`` — host runs ``uv`` against the bundled ``pyproject.toml``;
    ``mcp_config`` is OPTIONAL for uv, so it is omitted (no baked command,
    no baked interpreter). ``python`` — a ``user_config``-gated interpreter
    invokes ``-m srmech.mcp._cli``."""
    if server_type == "uv":
        return {"type": "uv", "entry_point": _SERVER_ENTRY_POINT}
    if server_type == "python":
        return {
            "type": "python",
            "entry_point": _SERVER_ENTRY_POINT,
            "mcp_config": {
                "command": "${user_config.python_path}",
                "args": ["-m", "srmech.mcp._cli"],
                "env": {},
            },
        }
    raise ValueError(
        f"unsupported server_type {server_type!r}; expected 'uv' or 'python'"
    )


def _user_config_block(server_type: str) -> Optional[Dict[str, Any]]:
    """The ``user_config`` block — only the ``python`` fallback needs one
    (the interpreter path). ``uv`` returns ``None`` (host manages
    Python)."""
    if server_type != "python":
        return None
    return {
        "python_path": {
            "type": "string",
            "title": "Python interpreter",
            "description": (
                "Path to a Python (>=3.10) interpreter with `srmech` "
                "installed (pip install srmech). uv-type bundles avoid "
                "this; use python-type only when uv is unavailable."
            ),
            "required": True,
            "default": "python3",
        }
    }


def _bundle_pyproject_toml() -> str:
    """Minimal ``[project]`` whose only dependency is ``srmech`` pinned to
    the emitting ``__version__`` — so ``uv`` resolves the exact platform
    wheel that carries ``libsrmech`` at install time. Version DERIVED, not
    hardcoded."""
    from ..version import __version__ as srmech_version

    return (
        "[project]\n"
        'name = "srmech-mcpb-runner"\n'
        'version = "0.0.0"\n'
        'requires-python = ">=3.10"\n'
        f'dependencies = ["srmech=={srmech_version}"]\n'
    )


