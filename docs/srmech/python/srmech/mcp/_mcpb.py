def build_manifest(
    *,
    name: str = _DEFAULT_NAME,
    server_type: str = "uv",
    name_filter: Optional[Callable[[str], bool]] = None,
) -> Dict[str, Any]:
    """Build the ``.mcpb`` ``manifest.json`` dict ENTIRELY from srmech
    introspection.

    ``version`` is ``srmech.__version__`` (never a literal); ``tools[]``
    is built from the ADVERTISED tool surface (``mcp_callable`` subset,
    honouring ``name_filter``), so a future handle-pending tool cannot
    silently desync the manifest. A srmech-extension ``attestation`` block
    (MPR-style) carries the version + a content hash of the full tool
    schema (the MPM crystallisation per CLAUDE.md §2).

    Parameters
    ----------
    name
        Bundle + server name (default ``srmech``).
    server_type
        ``"uv"`` (default; host fetches the platform wheel via uv) or
        ``"python"`` (``user_config``-gated interpreter fallback).
    name_filter
        Optional ``str -> bool`` predicate; only matching tool names are
        advertised. Wired to the ``--filter`` CLI flag.
    """
    assert server_type in ("uv", "python"), (
        "server_type must be 'uv' or 'python'"
    )
    from ..version import __version__ as srmech_version
    from ..introspect.tool_schema import get_tool_schema

    defs = _advertised_tool_defs(name_filter=name_filter)
    # v0.9.0rc410 (`#T1085`) — the ATTESTED count. `defs` is the ADVERTISED
    # surface, which legitimately includes any active profile's tools: the
    # server really will serve them, and the spec's `tools[]` must describe what
    # is served. The attestation is a different claim with a different scope —
    # it says what SRMECH vouches for — so it counts only rows srmech owns.
    # The two are equal on every clean host; they differ exactly when a profile
    # is active, which is precisely the case the old `len(defs)` got wrong.
    _owned_names = {t.name for t in _owned_tool_schema().tools}
    owned_def_count = sum(1 for d in defs if d["name"] in _owned_names)

    manifest: Dict[str, Any] = {
        "manifest_version": _MANIFEST_VERSION,
        "name": name,
        "version": srmech_version,  # DERIVED — never a literal
        "description": (
            "srmech (Stored-Relationship Mechanism) MCP server — exposes "
            f"{len(defs)} attested AMSC/QM cascade tools (14-class A-N "
            "vocabulary) to Claude Desktop. Each tools/call carries an "
            "MPR attestation block."
        ),
        "author": {
            "name": "Steven Kirkland",
            "url": "https://github.com/lemonforest/mlehaptics",
        },
        "homepage": (
            "https://github.com/lemonforest/mlehaptics/tree/main/docs/"
            "srmech/python"
        ),
        "documentation": (
            "https://github.com/lemonforest/mlehaptics/blob/main/docs/"
            "srmech/srmech_research_notebook.md"
        ),
        "license": "MIT",
        "keywords": ["mcp", "srmech", "spectral", "amsc", "cascade"],
        "server": _server_block(server_type),
        # tools[] element = {name (required), description (optional)} per
        # spec; built from the ADVERTISED iterator, not a frozen literal.
        "tools": [
            {"name": d["name"], "description": d["description"]} for d in defs
        ],
        # srmech advertises its FULL set statically -> false.
        "tools_generated": False,
        "compatibility": {
            "claude_desktop": ">=0.10.0",
            "platforms": ["darwin", "win32", "linux"],
            "runtimes": {"python": ">=3.10"},
        },
        # srmech EXTENSION top-level key — the MPM crystallisation. The
        # spec is permissive (all non-required top-level fields optional);
        # Claude Desktop ignores unknown keys.
        "attestation": {
            "mpr_version": "1.0",
            "srmech_version": srmech_version,
            "tool_schema_version": get_tool_schema().tool_schema_version,
            "tool_count": owned_def_count,
            "tool_schema_sha256": _tool_schema_hash(),  # 64-hex
            "parser_version": f"srmech {srmech_version}",
            "generated_at": _utc_now_iso(),
            "generator": "srmech mcp emit-mcpb",
        },
    }
    uc = _user_config_block(server_type)
    if uc is not None:
        manifest["user_config"] = uc
    return manifest


# ──────────────────────────────────────────────────────────────────────
# Public: pack_mcpb
# ──────────────────────────────────────────────────────────────────────


def pack_mcpb(
    out_dir: str = ".",
    *,
    name: str = _DEFAULT_NAME,
    server_type: str = "uv",
    manifest_only: bool = False,
    name_filter: Optional[Callable[[str], bool]] = None,
) -> Path:
    """Write ``manifest.json`` and (unless ``manifest_only``) pack a
    ``<name>.mcpb`` ZIP into ``out_dir``.

    The ``.mcpb`` is a stdlib-``zipfile`` ZIP whose ROOT carries
    ``manifest.json`` (required), plus ``pyproject.toml`` (uv reads it to
    resolve the platform wheel that carries ``libsrmech``) and
    ``server/main.py`` (the ``entry_point`` shim). No Node / mcpb
    toolchain is required.

    Returns the ABSOLUTE :class:`~pathlib.Path` of the written artifact
    (the ``.mcpb`` normally; ``manifest.json`` when ``manifest_only``)."""
    out = Path(out_dir).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)

    manifest = build_manifest(
        name=name, server_type=server_type, name_filter=name_filter
    )
    manifest_bytes = (
        json.dumps(manifest, indent=2, sort_keys=False) + "\n"
    ).encode("utf-8")
    manifest_path = out / "manifest.json"
    manifest_path.write_bytes(manifest_bytes)
    if manifest_only:
        return manifest_path.resolve()

    pyproject_bytes = _bundle_pyproject_toml().encode("utf-8")
    shim_bytes = _SERVER_SHIM.encode("utf-8")
    mcpb_path = out / f"{name}.mcpb"
    with zipfile.ZipFile(
        mcpb_path, "w", compression=zipfile.ZIP_DEFLATED
    ) as zf:
        zf.writestr("manifest.json", manifest_bytes)  # ROOT — REQUIRED
        zf.writestr("pyproject.toml", pyproject_bytes)
        zf.writestr("server/main.py", shim_bytes)  # entry_point
    return mcpb_path.resolve()


__all__ = ["build_manifest", "pack_mcpb"]
