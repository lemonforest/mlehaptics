"""F935 — the beat: harmonic(+1)/subharmonic(-1) = the_one's sigma=+1/-1 = the two time-directions = the
two NOWS. A FULL beat = both nows (the closed 2pi return); a HALF beat = one now (the snapshot). Grounded:
the_one(sigma,theta) carries dim=14 partition=(1,3,7,3) and sigma=+/-1 = the two directions. srmech rc58."""
from srmech.amsc import cascade
fwd=cascade.the_one(+1, 1, 6)   # harmonic / forward now
bwd=cascade.the_one(-1, 1, 6)   # subharmonic / backward now
print('the_one(+1, 1/6) [harmonic / forward now ] =', fwd)
print('the_one(-1, 1/6) [subharmonic / backward now]=', bwd)
print('=> sigma=+1 (harmonic, moves 0->+1) and sigma=-1 (subharmonic, moves 0->-1) are the two time-directions = the two NOWS.')
