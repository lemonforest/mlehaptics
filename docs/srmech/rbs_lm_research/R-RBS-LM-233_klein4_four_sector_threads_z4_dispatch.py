# (3) CAP-AT-4 — close the involution group; show Klein-4 has no 5th sector and no
#     order-4+ element; the 8+ rung needs the order-3 triality (F220).
# =====================================================================
def measure_cap_at_4(x):
    """Close the group of stream-transforms generated by {reverse (gamma5), signflip
    (iw7)} under composition and show:
      (a) it closes at EXACTLY 4 distinct transforms (the 4 Klein-4 sectors) — no 5th
          independent order-2 thread exists by these means;
      (b) Klein-4 = Z2 x Z2 has NO order-4+ element (every non-identity element is an
          involution: T(T(x)) == x) — so you cannot reach an 8-thread rung by composing
          order-2 sectors;
      (c) the only way past 4 is a genuinely ORDER-3 primitive — triality
          (qm.triality.triality_automorphism, tau^3=I, tau^2!=I), DEMONSTRATED order-3 here
          — exactly F220's cap. The ladder caps at 4 *before* triality."""
    xs = list(x)

    def canon(seq):
        # canonical fingerprint of a transform's action on the sample stream
        return tuple(round(float(v), 9) for v in seq)

    # BFS-close {identity, gamma5, iw7} under composition (exact, on the sample stream).
    gens = {
        "identity": lambda s: list(s),
        "gamma5_reverse": axis_gamma5,
        "iw7_signflip": axis_omega7,
    }
    seen = {canon(xs): "identity"}
    frontier = [(xs, "identity")]
    actions = list(gens.items())
    while frontier:
        cur, _name = frontier.pop()
        for gname, g in actions:
            nxt = g(cur)
            key = canon(nxt)
            if key not in seen:
                seen[key] = gname
                frontier.append((nxt, gname))
    group_order = len(seen)                                  # expect 4 (the Klein-4 sectors)

    # every non-identity sector transform is an INVOLUTION (order 2): T(T(x)) == x.
    involution_ok = {}
    for s in (1, 2, 3):
        once = klein4_stream_transform(s, xs)
        twice = klein4_stream_transform(s, once)
        involution_ok[s] = bool(max(
            (cascade.magnitude(float(a) - float(b)) for a, b in zip(twice, xs)),
            default=0.0) < 1e-12)
    all_involutions = all(involution_ok.values())

    # a 5th INDEPENDENT sector by order-2 means? -> the group closed at 4; any further
    # composition lands back in the 4 -> NO 5th distinct sector.
    fifth_independent_sector_exists = group_order > 4

    # the order-3 cap primitive: triality is order-3 (tau^3=I, tau^2!=I) — NOT reachable by
    # composing order-2 involutions (F220: the lean order-2 atoms generate a 2-group Z2^3).
    tau = np.asarray(qm.triality.triality_automorphism())
    I = np.eye(tau.shape[0], dtype=tau.dtype)
    t2 = tau @ tau
    t3 = t2 @ tau
    triality_is_order3 = bool(np.allclose(t3, I) and not np.allclose(t2, I)
                              and not np.allclose(tau, I))

    return {
        "involution_group_order": int(group_order),          # 4 == the Klein-4 sectors
        "caps_at_4": bool(group_order == 4),
        "every_nonidentity_sector_is_involution": bool(all_involutions),
        "per_sector_involution_ok": {SECTOR_LABELS[s]: involution_ok[s] for s in (1, 2, 3)},
        "fifth_independent_order2_thread_exists": bool(fifth_independent_sector_exists),
        "klein4_has_no_order4_element": bool(all_involutions and group_order == 4),
        "triality_dim": list(tau.shape),
        "triality_is_order3": triality_is_order3,             # the ONLY way past 4 (F220)
        "beyond_4_needs_order3_triality": bool(
            group_order == 4 and all_involutions and triality_is_order3),
    }


