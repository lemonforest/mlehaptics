def run_sector_independent(body, sector, x):
    """PARALLEL model: sector-thread runs its OWN evaluation on its OWN sector-transformed
    stream, reading NOTHING from any other thread's buffer (F232 run_pair_independent
    generalized). Returns (result, tracer)."""
    tr = DependencyTracer()
    t_in = klein4_stream_transform(sector, list(x))   # this thread's OWN transformed input
    for _ in t_in:
        tr.read_own()                                 # sourced from its own stream
    core = body(t_in)                                 # its OWN independent body evaluation
    result = klein4_stream_inverse(sector, core)      # un-transform -> the sector dual
    return result, tr


def run_sector_shared(body, sector, x, forward_buffer):
    """SERIAL model: sector-thread REUSES thread-0's forward result buffer and merely
    post-processes it by the sector mask (F232 run_pair_shared generalized). Every read is
    sourced from thread-0 -> forced-serial -> NOT an independent thread. Returns
    (result, tracer)."""
    tr = DependencyTracer()
    masked = klein4_stream_inverse(sector, list(forward_buffer))  # post-process A's OUTPUT
    for _ in masked:
        tr.read_shared()                                          # sourced from A's buffer
    result = klein4_stream_transform(sector, masked)              # the chiral_dual shape
    return result, tr


def measure_independence_4way(body, x):
    """For each of the 4 Klein-4 sectors: does the INDEPENDENT construction (own
    transformed stream, 0 cross-thread reads) reproduce the canonical sector-dual
    BIT-EXACT? A genuine 4th thread has cross_thread_reads == 0 and reproduces its dual."""
    forward = body(list(x))                                       # thread-0 forward (sector 0)

    def max_dev(a, b):
        # max |a_i - b_i| as a Class-K magnitude residual (diagnostic, not a sign-fold) ->
        # cascade.magnitude per HARD rule (no abs()).
        return max((cascade.magnitude(float(ai) - float(bi)) for ai, bi in zip(a, b)),
                   default=0.0)

    per_sector = {}
    for s in (0, 1, 2, 3):
        truth = sector_dual_canonical(body, s, list(x))           # the canonical sector dual
        r_ind, tr_ind = run_sector_independent(body, s, x)
        r_sh, tr_sh = run_sector_shared(body, s, x, forward)
        ind_ok = max_dev(r_ind, truth) < 1e-12
        sh_ok = max_dev(r_sh, truth) < 1e-12
        per_sector[s] = {
            "sector_label": SECTOR_LABELS[s],
            "independent_reproduces_sector_dual": bool(ind_ok),
            "shared_reproduces_sector_dual": bool(sh_ok),
            "cross_thread_reads_independent": int(tr_ind.shared_reads),
            "own_reads_independent": int(tr_ind.own_reads),
            "max_dev_independent_vs_truth": max_dev(r_ind, truth),
            "genuine_independent_thread": bool(ind_ok and tr_ind.shared_reads == 0),
        }
    all_four_independent = all(v["genuine_independent_thread"] for v in per_sector.values())
    return per_sector, all_four_independent


