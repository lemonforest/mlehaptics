# (4) USEFULNESS — the F232 condition generalized: 4 distinct iff bi-axially sensitive.
# =====================================================================
def measure_usefulness_4way(body, x):
    """Compute the 4 sector-duals and count DISTINCT results. Tag each with its Klein-4
    sector occupancy (Class M klein4_sector_count) and mutual klein4_similarity. The 4
    sectors give 4 DISTINCT (useful) results iff the body is sensitive to BOTH axes; they
    COLLAPSE on any axis the body is symmetric under (iw7-even -> 4->2; bi-even -> 4->1)."""
    duals = {s: sector_dual_canonical(body, s, list(x)) for s in (0, 1, 2, 3)}

    def max_dev(a, b):
        return max((cascade.magnitude(float(ai) - float(bi)) for ai, bi in zip(a, b)),
                   default=0.0)

    # group sectors into equivalence classes by bit-exact equality (the distinct results)
    reps = []                                                # list of (rep_sector, members)
    for s in (0, 1, 2, 3):
        placed = False
        for grp in reps:
            if max_dev(duals[s], duals[grp[0]]) < 1e-12:
                grp.append(s)
                placed = True
                break
        if not placed:
            reps.append([s])
    n_distinct = len(reps)

    # net handedness per sector (Class C) — the chirality each sector-thread carries
    def net_hand(seq):
        orients = [cascade.pin_slot_at_zero(float(v))[0] for v in seq]
        return int(cascade.net_chirality(orients))

    net_hands = {SECTOR_LABELS[s]: net_hand(duals[s]) for s in (0, 1, 2, 3)}

    # Klein-4 sector tag for each thread (Class M): an all-`s` Klein-4 vector occupies
    # exactly sector s (the substrate attestation that the 4 threads are the 4 sectors).
    D = 8
    sector_tags = {}
    for s in (0, 1, 2, 3):
        vec = np.full(D, s, dtype=int)
        sector_tags[SECTOR_LABELS[s]] = [int(c) for c in np.asarray(hdc.klein4_sector_count(vec))]

    # mutual Klein-4 similarity of the 4 pure-sector tags (orthogonal -> 0.0 off-diagonal)
    pure = {s: np.full(D, s, dtype=int) for s in (0, 1, 2, 3)}
    sim_offdiag_max = max(
        hdc.klein4_similarity(pure[a], pure[b]) for a in (0, 1, 2, 3) for b in (0, 1, 2, 3)
        if a != b)

    collapse = {4: "bi-axially sensitive (USEFUL: 4 distinct results)",
                2: "symmetric under one axis (4 collapse to 2)",
                1: "symmetric under both axes (4 collapse to 1 — fully redundant)"}
    return {
        "n_distinct_sector_results": n_distinct,
        "distinct_classes": [[SECTOR_LABELS[s] for s in grp] for grp in reps],
        "useful_4_distinct": bool(n_distinct == 4),
        "collapse_reading": collapse.get(n_distinct, f"{n_distinct} distinct"),
        "net_handedness_per_sector": net_hands,
        "klein4_sector_tags": sector_tags,
        "klein4_pure_sector_offdiag_similarity_max": round(float(sim_offdiag_max), 6),
        "dual_heads": {SECTOR_LABELS[s]: [round(float(v), 4) for v in duals[s][:4]]
                       for s in (0, 1, 2, 3)},
    }


