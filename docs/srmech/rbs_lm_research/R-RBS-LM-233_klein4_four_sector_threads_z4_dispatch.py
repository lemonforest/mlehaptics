def kuramoto_ring_step(theta, omega, k_matrix, alpha, dt):
    """One Euler step on the Sakaguchi-Kuramoto coupling (F231's EXACT convention):
        dtheta_i/dt = omega_i + (1/N) sum_j K_ij sin(theta_j - theta_i - alpha).
    With a RING k_matrix (k[i,i+-1]=2.0, F231) and alpha=pi/2 this is the frustration
    that locks into the Z4 traveling-wave SPLAY [0,.25,.5,.75] (F231 Result 3). sin via
    laplacian.elementwise_transcendental (Class L libm SSoT). Reuses F231's machinery
    verbatim so the demonstrated splay reproduces."""
    n = len(theta)
    phase_diff = theta[None, :] - theta[:, None] - alpha     # [i,j] = theta_j - theta_i - alpha
    sin_pd = lap.elementwise_transcendental(phase_diff.reshape(-1), "sin").reshape(n, n)
    interaction = (k_matrix * sin_pd).sum(axis=1) / n
    return theta + dt * (omega + interaction)


def order_parameter_magnitude(theta):
    """Kuramoto r = |(1/N) sum exp(i theta)|; exp_i via srmech (Class L), modulus via two
    Class-K cascade.magnitude calls + hypot (never python abs())."""
    z = lap.elementwise_transcendental(theta, "exp_i").mean()
    re = cascade.magnitude(float(z.real))
    im = cascade.magnitude(float(z.imag))
    return float(np.sqrt(re ** 2 + im ** 2))


def wrap_phase(theta):
    z = lap.elementwise_transcendental(theta, "exp_i")
    return np.angle(z)


def relative_phase_fractions(theta):
    """Phase of each oscillator relative to oscillator 0, as a fraction of 2pi in [0,1).
    The Z4 splay target is [0, .25, .5, .75]."""
    fracs = []
    for i in range(len(theta)):
        rel = float(theta[i]) - float(theta[0])
        rel = rel - TWO_PI * np.floor(rel / TWO_PI)
        fracs.append(rel / TWO_PI)
    return fracs


def measure_z4_splay():
    """4 cascade-clocks coupled as a Sakaguchi alpha=pi/2 RING -> the Z4 (cyclic-order-4)
    quarter-turn splay. Seeded near the traveling-wave basin (F231 honest caveat (a): the
    splay is one of several locked attractors; we seed near it). The dispatch slots are the
    Z4 = Z/4 round-robin via Class N quantization + Class I (cyclic.mod_add) — DISTINCT from
    the Klein-4 sector identity (Z4 != Klein-4)."""
    n = 4
    omega = np.full(n, 1.0)                                  # identical -> coupling-driven splay
    # F231's EXACT ring + seed: k[i,i+-1]=2.0, seed ON the traveling-wave basin 2*pi*k/N.
    k_matrix = np.zeros((n, n))
    for i in range(n):
        k_matrix[i, (i + 1) % n] = 2.0
        k_matrix[i, (i - 1) % n] = 2.0
    alpha, T, dt = np.pi / 2.0, 200.0, 0.02
    theta = np.array([TWO_PI * k / n for k in range(n)])     # the splay basin (F231)
    n_steps = int(T / dt)
    tail_start = int(n_steps * 0.8)
    r_tail, frac_tail = [], []
    for k in range(n_steps):
        theta = kuramoto_ring_step(theta, omega, k_matrix, alpha, dt)
        theta = wrap_phase(theta)
        if k >= tail_start:
            r_tail.append(order_parameter_magnitude(theta))
            frac_tail.append(relative_phase_fractions(theta))
    final_r = float(np.mean(r_tail))
    final_fracs = list(np.mean(np.array(frac_tail), axis=0))
    # Z4 dispatch slots: quantize each fraction to /4 (Class N) and fold onto Z/4 (Class I).
    slots = []
    for f in final_fracs:
        p, q = rat.best_rational(int(round(f * 4)), 4, 4)     # Class N: nearest /4 slot
        slot = cyclic.mod_add(int(round((p / q) * 4)) if q else 0, 0, 4)  # Class I: Z/4
        slots.append(int(slot))
    target = [0.0, 0.25, 0.5, 0.75]
    # max deviation of the SORTED fractions from the splay (rotation-invariant): the four
    # phases occupy the four quarter-turn slots regardless of which thread leads.
    sorted_fracs = sorted(final_fracs)
    dev = max(cascade.magnitude(a - b) for a, b in zip(sorted_fracs, target))
    distinct_slots = len(set(slots))
    return {
        "final_r": round(final_r, 4),
        "relative_phase_fractions": [round(f, 4) for f in final_fracs],
        "sorted_fractions": [round(f, 4) for f in sorted_fracs],
        "z4_dispatch_slots": slots,
        "n_distinct_slots": distinct_slots,
        "splay_target": target,
        "max_dev_from_splay": round(dev, 4),
        "z4_splay_locked": bool(dev < 0.05 and distinct_slots == 4),
        "note_r_zero_is_splay_signature": "r~0 because 4 phases evenly spread cancel (F231)",
    }


def ring_coupling_spectrum(n=4):
    """The 4-oscillator ring IS a graph (Class L, F121). Build its Laplacian via
    dense_laplacian (positive edge weights via cascade.magnitude, never abs()) and read the
    spectrum via jacobi_eigvals. A 4-cycle has one zero eigenvalue (one component)."""
    edges, weights = [], []
    for i in range(n):
        j = (i + 1) % n
        a, b = (i, j) if i < j else (j, i)
        edges.append((a, b))
        weights.append(cascade.magnitude(1.0))               # unit ring coupling (Class K)
    L = lap.dense_laplacian(n, edges, weights)
    eig = sorted(float(e) for e in lap.jacobi_eigvals(L))
    n_zero = sum(1 for e in eig if cascade.magnitude(e) < 1e-9)
    fiedler = eig[1] if len(eig) > 1 else 0.0
    return eig, n_zero, float(fiedler)


