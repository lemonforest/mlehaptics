"""R-RBS-LM-27 — ASL gloss smoke: does the cascade pick context-sensitive signs?

Loads the v27 ASL-gloss instrument. For each test prompt, builds the
inference signature `<english>\\x02` and asks the cascade for the next
~80 bytes — what gloss does it produce?

The crucial test is POLYSEMY:
  "I beat the eggs"  → does it produce /beat-egg/ ?
  "I beat the dog"   → does it produce /beat-hit/ ?
  "She beat me"      → does it produce /beat-defeat/ ?
  "The drum beats"   → does it produce /beat-rhythm/ ?

Honest expectation: at 1324 observations on 74 pairs the cascade likely
still mode-collapses to the most-frequent gloss byte transitions. But
even if mode-collapsed, the SURFACE works — the cascade accepts the
prompt format, produces gloss-like outputs, and the OpenAI-API extension
delivers them. Surface ≠ knowledge per R-RBS-LM-25 §5 Finding 8.

Usage:
    ~/.venvs/rbs-lm-research/bin/python \\
        docs/srmech/rbs_lm_research/asl_smoke.py
"""

import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "python"))
sys.path.insert(0, str(HERE))

from rbs_lm_chatbot import RBSChatbotBytes  # noqa: E402


INSTRUMENT_PATH = "docs/srmech/rbs_lm_research/rbs_lm_instrument_v27_asl_gloss.bin"
SEPARATOR_BYTE = 0x02
END_PAIR_BYTE = 0x03


# Polysemy stress-test: each row tests one English word with multiple meanings.
# Expected ASL signs are NOT used by the cascade — they're for our review.
POLYSEMY_TESTS = [
    {
        "english": "I beat the eggs",
        "expected_sign_contains": "beat-egg",
        "polysemy_word": "beat",
    },
    {
        "english": "She beat me",
        "expected_sign_contains": "beat-defeat",
        "polysemy_word": "beat",
    },
    {
        "english": "My heart beats",
        "expected_sign_contains": "beat-pulse",
        "polysemy_word": "beat",
    },
    {
        "english": "The drum has a beat",
        "expected_sign_contains": "beat-rhythm",
        "polysemy_word": "beat",
    },
    {
        "english": "She runs every morning",
        "expected_sign_contains": "run-jog",
        "polysemy_word": "run",
    },
    {
        "english": "The machine runs",
        "expected_sign_contains": "run-machine",
        "polysemy_word": "run",
    },
    {
        "english": "Water runs from the tap",
        "expected_sign_contains": "run-flow",
        "polysemy_word": "run",
    },
    {
        "english": "Turn on the light",
        "expected_sign_contains": "light-bright",
        "polysemy_word": "light",
    },
    {
        "english": "This box is light",
        "expected_sign_contains": "light-weight",
        "polysemy_word": "light",
    },
    {
        "english": "Turn right at the corner",
        "expected_sign_contains": "right-direction",
        "polysemy_word": "right",
    },
    {
        "english": "That is right",
        "expected_sign_contains": "right-correct",
        "polysemy_word": "right",
    },
]

# Basic-greeting + non-polysemy smoke
BASIC_TESTS = [
    "Hello",
    "Thank you",
    "I love you",
    "What is your name?",
    "I don't know",
    "It is raining",
]


def translate(bot, english, max_new=80):
    """Build inference signature `<english>\\x02` and let the cascade
    generate. Stop at END_PAIR_BYTE (\\x03) or max_new, whichever first."""
    prompt_bytes = list(english.encode("utf-8")) + [SEPARATOR_BYTE]
    # Use the bot's internal _generate directly so we can pass byte-mode prompt
    from rbs_lm_encoder import CONTEXT_WINDOW, D, bind
    from rbs_lm_bytes import encode_context_bytes, vectorised_cleanup_bytes

    tokens = list(prompt_bytes)
    new_bytes = []
    latencies = []
    for _ in range(max_new):
        t0 = time.time()
        ctx = tokens[-CONTEXT_WINDOW:] if len(tokens) > CONTEXT_WINDOW else tokens
        ctx_vec = encode_context_bytes(ctx, bot.vocab_table, D)
        cand = bind(bot.instrument, ctx_vec)
        res = vectorised_cleanup_bytes(cand, bot.vocab_table, D, top_k=1)
        nxt = res[0][0]
        latencies.append((time.time() - t0) * 1000)
        new_bytes.append(nxt)
        tokens.append(nxt)
        if nxt == END_PAIR_BYTE:
            break
    return new_bytes, latencies


def render_gloss_bytes(byte_list):
    """Decode generated bytes; strip ETX if present; render via errors=replace."""
    if byte_list and byte_list[-1] == END_PAIR_BYTE:
        byte_list = byte_list[:-1]
    return bytes(bytearray(byte_list)).decode("utf-8", errors="replace")


def main():
    print(f"=== R-RBS-LM-27 — ASL gloss smoke ===")
    print(f"  instrument: {INSTRUMENT_PATH}")
    if not Path(INSTRUMENT_PATH).exists():
        print(f"FATAL: instrument not found. Run encode_asl_corpus.py first.")
        sys.exit(1)

    bot = RBSChatbotBytes.load(instrument_path=INSTRUMENT_PATH, verbose=True)

    results = {"polysemy": [], "basic": []}

    # ---- Polysemy tests ---------------------------------------------------
    print(f"\n{'='*72}")
    print(f"=== Polysemy context-sensitivity test ===")
    print(f"  (does same English word produce DIFFERENT gloss signs in different contexts?)")
    print(f"{'='*72}")

    n_polysemy_hit = 0
    for t in POLYSEMY_TESTS:
        t0 = time.time()
        new_bytes, lats = translate(bot, t["english"])
        elapsed = (time.time() - t0) * 1000
        completion = render_gloss_bytes(new_bytes)
        hit = t["expected_sign_contains"] in completion
        n_polysemy_hit += hit
        print(f"\n  english:  {t['english']!r}")
        print(f"  expected: contains {t['expected_sign_contains']!r}")
        print(f"  gloss:    {completion!r}")
        print(f"  hit:      {'YES' if hit else 'no'}  ({elapsed:.0f} ms; {len(new_bytes)} bytes)")
        results["polysemy"].append({
            "english": t["english"],
            "expected_sign": t["expected_sign_contains"],
            "polysemy_word": t["polysemy_word"],
            "completion": completion,
            "hit": hit,
            "n_bytes": len(new_bytes),
            "elapsed_ms": elapsed,
        })

    print(f"\n  Polysemy hit rate: {n_polysemy_hit}/{len(POLYSEMY_TESTS)} "
          f"({100*n_polysemy_hit/len(POLYSEMY_TESTS):.0f}%)")

    # ---- Basic tests ------------------------------------------------------
    print(f"\n{'='*72}")
    print(f"=== Basic prompts ===")
    print(f"{'='*72}")

    for english in BASIC_TESTS:
        t0 = time.time()
        new_bytes, lats = translate(bot, english)
        elapsed = (time.time() - t0) * 1000
        completion = render_gloss_bytes(new_bytes)
        print(f"\n  english:  {english!r}")
        print(f"  gloss:    {completion!r}")
        print(f"  ({elapsed:.0f} ms; {len(new_bytes)} bytes)")
        results["basic"].append({
            "english": english,
            "completion": completion,
            "n_bytes": len(new_bytes),
            "elapsed_ms": elapsed,
        })

    # ---- Save -------------------------------------------------------------
    out_path = Path("docs/srmech/rbs_lm_research/asl_smoke_results.json")
    out_path.write_text(json.dumps({
        "partition": "R-RBS-LM-27",
        "instrument": INSTRUMENT_PATH,
        "polysemy_tests": results["polysemy"],
        "basic_tests": results["basic"],
        "polysemy_hit_count": n_polysemy_hit,
        "polysemy_total": len(POLYSEMY_TESTS),
    }, indent=2, ensure_ascii=False))
    print(f"\nResults: {out_path}")

    print(f"\n=== Honest framework reading ===")
    print(f"  Polysemy context-sensitivity: {n_polysemy_hit}/{len(POLYSEMY_TESTS)}")
    if n_polysemy_hit == 0:
        print(f"  → No context-sensitive disambiguation at this scale.")
        print(f"  → Cascade likely mode-collapsed; the SURFACE works but the")
        print(f"    polysemy signal is below the noise floor at 1324 obs.")
    elif n_polysemy_hit < len(POLYSEMY_TESTS) / 2:
        print(f"  → Partial polysemy signal — some disambiguation present.")
    else:
        print(f"  → Polysemy disambiguation working at majority rate.")


if __name__ == "__main__":
    main()
