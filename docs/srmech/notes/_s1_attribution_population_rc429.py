def eponym_candidates(paths, limit_files=None):
    """Generate ``<Capitalised> <object-noun>`` candidates for HUMAN vetting.

    This is a CANDIDATE GENERATOR, never a vocabulary. rc428 measured what
    happens when such a pass is trusted: its top hits were ``Crossref``,
    ``Iterable``, ``Optional``, ``Jun`` and ``Der``.
    """
    c = Counter()
    for p in (paths if limit_files is None else paths[:limit_files]):
        for _lineno, val in CC.string_constants(p):
            for m in _EPONYM_BIGRAM.finditer(CC._strip_code_spans(val)):
                head = m.group(1)
                if head in _NOT_A_PERSON:
                    continue
                c[head] += 1
    return c


# ── identifiers ───────────────────────────────────────────────────────

_DOI = re.compile(r"10\.\d{4,9}/[-._;()/:A-Za-z0-9]+")
_URL = re.compile(r"https?://\S+")
_ISBN = re.compile(r"\bISBN[- ]?[-0-9X ]{10,}", re.I)


def identifier_kinds(text):
    """Which identifier families does ``text`` carry? Empty = UNSOURCED."""
    out = []
    if CC._ARXIV.search(text):
        out.append("arxiv")
    if _DOI.search(text):
        out.append("doi")
    if _URL.search(text):
        out.append("url")
    if _ISBN.search(text):
        out.append("isbn")
    return out


# ── the matcher ───────────────────────────────────────────────────────

_WORDCH = re.compile(r"[0-9A-Za-z_]")
#: Suffixes that keep a match a real occurrence of the same word. Plurals and
#: possessives only — ``modular`` + ``ity`` is a DIFFERENT word and must not
#: pass, while ``Theta Function`` + ``s`` is the same term pluralised and must.
_OK_SUFFIX = ("", "s", "es", "'s", "’s")


def prose_occurrences(text, term):
    """Occurrences of ``term`` that are PROSE, not matcher artifacts.

    Two subtractions, each forced by a measured false positive in the rc429
    sample, and each a SYNTACTIC rule that names no file and no line:

    **B1 word boundary.** ``densify`` deletes whitespace so a term can cross a
    line wrap (``Cayley-\\n    Dickson``). The same deletion joins ADJACENT
    WORDS: ``of a non-negative`` densifies to ``ofanon-negative``, which
    contains ``fano``. Measured in the rc429 sample: ``Fano`` inside
    ``o[f a no]n-``, ``Bott`` inside ``Bott[om]-k``, ``F_4`` inside
    ``f_4[58]``. So a match must be bounded in the ORIGINAL text.

    **B2 identifier context.** A term inside a dotted or underscored
    identifier is CODE — ``srmech.physics.qm.triality``, ``triality_swap``,
    ``moufang_residue``, ``srmech_modular_forms_ring_represent``. This is
    rc428's axis A4 arriving from the other side: A4 blanks ``code spans``,
    and worked-example snippets carry bare identifiers with no span markers.

    Returns ``[(start, end, surface)]`` in ORIGINAL offsets.
    """
    stripped = CC._strip_code_spans(text)
    dense, idx = CC.densify_indexed(stripped)
    out = []
    for m in re.finditer(term_pattern_cached(term), dense, re.IGNORECASE):
        a, b = idx[m.start()], idx[m.end() - 1] + 1
        # B1 — the character before must not be a word character.
        if a > 0 and _WORDCH.match(stripped[a - 1]):
            continue
        # B2 left — a dotted-identifier prefix (``qm.triality``).
        if a > 0 and stripped[a - 1] == "." and a > 1 \
                and _WORDCH.match(stripped[a - 2]):
            continue
        # B1/B2 right — the trailing run must be a legal word suffix.
        j = b
        while j < len(stripped) and (_WORDCH.match(stripped[j])
                                     or stripped[j] in ".'’"):
            j += 1
        tail = stripped[b:j]
        if tail.rstrip(".") not in _OK_SUFFIX:
            continue
        out.append((a, b, text[a:b]))
    return out


@lru_cache(maxsize=256)
def term_pattern_cached(term):
    return CC.term_pattern(term)


def build_alt(terms):
    """One alternation over ``terms`` against DENSE text, groups keyed by index.

    Longest-first so ``exceptional Jordan`` wins over ``Jordan algebra``'s
    prefix and a nested term never masks its container.
    """
    ordered = sorted(terms, key=lambda t: (-len(t), t))
    pat = "|".join("(?P<t%d>%s)" % (i, CC.term_pattern(t))
                   for i, t in enumerate(ordered))
    return re.compile(pat, re.IGNORECASE), {"t%d" % i: t
                                            for i, t in enumerate(ordered)}


def terms_in(dense, alt, idx):
    return [idx[m.lastgroup] for m in alt.finditer(dense)]


