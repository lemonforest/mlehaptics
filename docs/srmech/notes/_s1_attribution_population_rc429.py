"""S1 rc429 (`#T1132`) — SIZING the unsourced-claim class: ATTRIBUTION vs MENTION.

WHAT THIS MEASURES
==================
rc428 shipped a gate that verifies *a cited source actually contains the cited
claim*. A claim with **no source** has nothing to check, so that gate cannot
see it by construction. This instrument sizes the blind class and asks the only
question that decides whether it can be gated at all:

    Of the shipped string constants that name a literature concept and carry no
    identifier, how many ATTRIBUTE (credit a result to a named source as its
    warrant) and how many merely MENTION (use a standard name for a standard
    object, the way "Fourier transform" is used)?

A gate that cannot tell those apart would demand citations on ~1.5k sites, and
the predictable response is to bolt a plausible reference onto each —
manufacturing exactly the hallucinated-citation defect the arc exists to kill.

THE UNIT IS AN AST STRING CONSTANT (rc428's finding, re-used not re-litigated)
=============================================================================
``citation_corpus.string_constants`` resolves implicit concatenation. A line
scanner invents phantom truncated identifiers in one direction and cannot see a
claim whose term and locator sit on different source lines in the other.
Falsifier F4 below MEASURES that difference in this tree rather than citing it.

TWO VOCABULARIES, AND WHY THE COUNT DEPENDS ON WHICH
=====================================================
``V_manifest`` — the 32 attested claim terms in
``amsc/attested/literature_claims/row.ndjson``. This is rc428's vocabulary and
the one the 536 figure refers to.

``V_eponym`` — a personal-eponym vocabulary, generated by a proper-noun +
mathematical-object-noun bigram pass and then HAND-VETTED. It exists because
``V_manifest`` is *source-derived*: it holds only terms belonging to the two
attested papers, so it **cannot contain "Calugareanu-White-Fuller"** — one of
the two known defects is invisible to it. That is a structural blind spot in
the population definition, not a tuning parameter, and F1b measures it.

Auto-extraction WITHOUT vetting was refuted at rc428 (top candidates were
``Crossref``, ``Iterable``, ``Optional``, ``Jun``, ``Der``), so the bigram pass
GENERATES candidates and a human decides; the vetted list is data in the
NDJSON, not a hidden constant.

DISCIPLINE
==========
* No stdlib ``math`` / ``fractions`` / ``decimal``; no numpy; no ``abs()``.
* Every falsifier is PRE-REGISTERED in :data:`PREREG` with its prediction
  before it runs, and every null is classified REFUTED / BOUNDED / EMPTY /
  UNSUPPORTED.
* Controls are ASSERTED, not merely computed — :func:`_controls` raises. rc428
  D1 shipped an instrument that computed four controls and read one, and
  ``main()`` returned 0 while printing DEAD SEAM.
* Hand labels are written FIRST (``STAGE=sample``) and scored SECOND
  (``STAGE=score``), so no discriminator can be tuned against a label it has
  already seen.

USAGE
=====
    PYTHONPATH=docs/srmech/python SRMECH_EXPECT_PURE=1 \\
        python3 docs/srmech/notes/_s1_attribution_population_rc429.py sample
    ... hand-label into _s1_attribution_labels_rc429.json ...
    PYTHONPATH=docs/srmech/python SRMECH_EXPECT_PURE=1 \\
        python3 docs/srmech/notes/_s1_attribution_population_rc429.py score
"""

