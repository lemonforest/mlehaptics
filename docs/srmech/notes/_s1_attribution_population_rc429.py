class Site:
    """One string constant that names a claim term and carries no identifier."""

    __slots__ = ("path", "line", "text", "terms", "in_docstring", "sid",
                 "identifiers", "prose_terms")

    def __init__(self, path, line, text, terms, in_docstring, identifiers):
        self.path = path
        self.line = line
        self.text = text
        self.terms = terms
        self.in_docstring = in_docstring
        #: Which identifier families this constant carries. EMPTY = unsourced.
        self.identifiers = identifiers
        #: The subset of :attr:`terms` that survives B1/B2 as PROSE.
        self.prose_terms = []
        # Class A content-addressing: the site's identity IS its content hash.
        self.sid = sha256_bytes(
            ("%s|%d|%s" % (path, line, text)).encode("utf-8"))

    @property
    def unsourced(self):
        return not self.identifiers

    def as_row(self, quote=400):
        return {
            "site_id": self.sid[:16], "path": self.path, "line": self.line,
            "terms": sorted(set(self.terms)),
            "prose_terms": list(self.prose_terms),
            "in_docstring": self.in_docstring,
            "identifiers": self.identifiers,
            "chars": len(self.text),
            "quote": self.text[:quote],
        }


def docstring_lines(path):
    tree = ast.parse(path.read_bytes(), filename=str(path))
    out = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef,
                             ast.AsyncFunctionDef, ast.ClassDef)):
            b = node.body
            if (b and isinstance(b[0], ast.Expr)
                    and isinstance(b[0].value, ast.Constant)
                    and isinstance(b[0].value.value, str)):
                out.add(b[0].value.lineno)
    return out


def population(paths, alt, idx):
    """EVERY claim-term site (sourced or not), plus the totals a count needs.

    Returns the whole term-bearing set rather than only the unsourced subset,
    because the positive control has to be able to find a site that turned out
    to BE sourced — which is exactly what happened to ``malcev_defect`` at
    rc428, and an instrument holding only the unsourced subset reports that as
    "the corpus is wrong" instead of as the finding it is.
    """
    sites, tot = [], Counter()
    for p in paths:
        rel = p.relative_to(CC.PKG_ROOT).as_posix()
        docs = docstring_lines(p)
        for lineno, val in CC.string_constants(p):
            tot["str_constants"] += 1
            hits = terms_in(CC.densify(val), alt, idx)
            if not hits:
                continue
            tot["with_term"] += 1
            ids = identifier_kinds(val)
            if ids:
                tot["with_identifier"] += 1
            else:
                tot["unsourced"] += 1
                tot["unsourced_term_pairs"] += len(set(hits))
                tot["unsourced_term_occurrences"] += len(hits)
            s = Site(rel, lineno, val, hits, lineno in docs, ids)
            # B1/B2-corrected: does any hit survive as PROSE?
            s.prose_terms = sorted({t for t in set(hits)
                                    if prose_occurrences(val, t)})
            if not ids:
                if s.prose_terms:
                    tot["unsourced_prose"] += 1
                else:
                    tot["unsourced_all_artifact"] += 1
            sites.append(s)
    return sites, tot


def unsourced_of(sites):
    return [s for s in sites if s.unsourced]


# ── DISCRIMINATORS — pre-registered, scored, never tuned ───────────────
# Each takes a Site and returns True ("this ATTRIBUTES") or False.

_CREDIT = re.compile(
    r"\b(due to|after|following|per|proved|proves|proven|showed|shows|"
    r"established|introduced|attributed to|according to|cited|citing|"
    r"cites|states|asserts|derives from|goes back to|is named for|"
    r"named after|theorem of|result of|construction of)\b", re.I)
_YEAR = re.compile(r"\((?:1[6-9]\d{2}|20[0-4]\d)\)")
_POSSESSIVE = re.compile(r"\b%s%s{2,}(?:'s|’s)\b" % (_CAP, _LOW))
_REFBLOCK = re.compile(
    r"\b(References?|Citations?|Bibliograph|Provenance|SSoT|SSOT|cite_as|"
    r"Source|Attribution|See also|Further reading)\b\s*[:—-]", re.I)
_BIBSHAPE = re.compile(
    #: ``Baez, J.C. (`` — an author-initials-year byline
    (r"%s%s+,\s*%s\.(?:\s*%s\.)?\s*\(" % (_CAP, _LOW, _CAP, _CAP))
    #: ``*An Introduction to Nonassociative Algebras*`` — an italic title
    + r"|\*[^*]{6,}\*"
    #: ``ch. III`` — a chapter locator
    + r"|\bch\.\s*[IVXLC0-9]"
    #: publisher / journal apparatus
    + r"|\b(?:Press|Univ\.|University|Springer|Wiley|Elsevier"
      r"|Bull\.|Trans\.|Amer\.|Soc\.)\b")


def d1_possessive(site):
    """A capitalised name in POSSESSIVE form — ``CWF's writhe``, ``Baez's``."""
    return _POSSESSIVE.search(CC._strip_code_spans(site.text)) is not None


def d2_year(site):
    """A parenthesised publication year — ``(1966)``, ``(2002)``."""
    return _YEAR.search(site.text) is not None


def d3_credit_verb(site):
    """A credit verb or preposition — ``due to`` / ``proved`` / ``states``."""
    return _CREDIT.search(CC._strip_code_spans(site.text)) is not None


def d4_eponym_vocab(site):
    """A PERSONAL eponym is present, matched the rc428 way (dense).

    Kept in its ORIGINAL dense form even after B1/B2 was discovered, so the
    correction's value is MEASURED against :func:`d4b_eponym_vocab_prose`
    rather than asserted. Silently upgrading it would have deleted the
    evidence that the fix mattered.
    """
    dense = CC.densify(site.text)
    return any(re.search(term_pattern_cached(e), dense, re.IGNORECASE)
               for e in V_EPONYM)


def d4b_eponym_vocab_prose(site):
    """The same vocabulary under B1/B2 — the eponym must occur as PROSE."""
    return any(prose_occurrences(site.text, e) for e in V_EPONYM)


def d8_prose_term_present(site):
    """Any manifest claim term survives B1/B2 — i.e. the site is not artifact."""
    return bool(site.prose_terms)


#: A stated relation: an identity written out, rather than merely named.
_RELATION = re.compile(r"[=≡≅≈]|\\equiv|\bmod\s*2\b")


def d9_bare_eponym_relation(site):
    """POST-HOC. A personal eponym as prose, NO bibliographic apparatus, and a
    RELATION stated in the same string.

    Written after F8 REFUTED the best sample-scored discriminator on both
    known defects, to describe the sub-class those defects actually belong to:
    a theorem NAMED by its eponym, its content ASSERTED, and nothing behind
    it. Reported as post-hoc, and — see the F10 record — it cannot be
    validated on this sample, which drew zero members of the sub-class.
    """
    return (d4b_eponym_vocab_prose(site)
            and not (d2_year(site) or d5_ref_block(site) or d6_bib_shape(site))
            and _RELATION.search(site.text) is not None)


def d5_ref_block(site):
    """The string carries a References / Provenance / SSoT header."""
    return _REFBLOCK.search(site.text) is not None


def d6_bib_shape(site):
    """Bibliographic apparatus — ``Author, I. (``, ``*Title*``, ``ch. III``."""
    return _BIBSHAPE.search(CC._strip_code_spans(site.text)) is not None


def d7_module_has_identifier(site, modules_with_ids):
    """The site's MODULE cites an identifier somewhere — proximity proxy."""
    return site.path in modules_with_ids


