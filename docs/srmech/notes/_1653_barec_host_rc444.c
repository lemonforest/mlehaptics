static const srmech_toml_value_t *tv_get(const srmech_toml_value_t *t,
                                         const char *key)
{
    assert(key != NULL);
    assert(key[0] != '\0');
    if (t == NULL || t->type != SRMECH_TOML_TABLE) { return NULL; }
    return srmech_toml_table_get(t, key);
}

/* The n-th entry of an array-of-tables, tolerating the single-table spelling
 * TOML produces when only one [[x]] block exists in some writers. */
static const srmech_toml_value_t *tv_entry(const srmech_toml_value_t *v,
                                           uint32_t idx, uint32_t *out_n)
{
    assert(out_n != NULL);
    assert(idx < 0x7fffffffu);
    if (v == NULL) { *out_n = 0u; return NULL; }
    if (v->type == SRMECH_TOML_TABLE) {
        *out_n = 1u;
        return (idx == 0u) ? v : NULL;
    }
    if (v->type != SRMECH_TOML_ARRAY) { *out_n = 0u; return NULL; }
    *out_n = v->u.arr.n;
    return (idx < v->u.arr.n) ? v->u.arr.items[idx] : NULL;
}

static int tv_str(const srmech_toml_value_t *t, const char *key,
                  const char **p, uint32_t *n)
{
    const srmech_toml_value_t *m = tv_get(t, key);
    assert(p != NULL && n != NULL);
    assert(key != NULL);
    if (m == NULL || m->type != SRMECH_TOML_STRING) { return 0; }
    *p = m->u.str.ptr;
    *n = m->u.str.len;
    return 1;
}

static srmech_status_t slurp(const char *path, char *buf, size_t cap,
                            size_t *out_len)
{
    FILE *fp;
    size_t n;
    assert(path != NULL);
    assert(buf != NULL && out_len != NULL && cap > 0u);
    fp = fopen(path, "rb");
    if (fp == NULL) { return SRMECH_ERR_IO; }
    n = fread(buf, 1u, cap, fp);
    (void)fclose(fp);
    if (n == 0u) { return SRMECH_ERR_IO; }
    if (n >= cap) { return SRMECH_ERR_OVERFLOW; }
    buf[n] = '\0';
    *out_len = n;
    return SRMECH_OK;
}

static const srmech_json_value_t *j_parse(const char *s, size_t n,
                                          void *ws, size_t wsn)
{
    srmech_json_value_t *t = NULL;
    assert(s != NULL);
    assert(ws != NULL && wsn > 0u);
    if (srmech_json_parse(s, n, ws, wsn, &t) != SRMECH_OK) { return NULL; }
    return t;
}

static int j_str(const srmech_json_value_t *o, const char *key,
                 const char **p, uint32_t *n)
{
    const srmech_json_value_t *m;
    assert(key != NULL);
    assert(p != NULL && n != NULL);
    if (o == NULL || o->type != SRMECH_JSON_OBJECT) { return 0; }
    m = srmech_json_object_get(o, key);
    if (m == NULL || m->type != SRMECH_JSON_STRING) { return 0; }
    *p = m->u.str.ptr;
    *n = m->u.str.len;
    return 1;
}

