static int op_in_c_table(const char *s, uint32_t n)
{
    int i;
    assert(s != NULL || n == 0u);
    assert(n < 4096u);
    for (i = 0; i < 10; i++) {
        size_t l = strlen(C_RUN_OPS[i]);
        if (l == (size_t)n && memcmp(s, C_RUN_OPS[i], l) == 0) { return 1; }
    }
    return 0;
}

/* Step form per compose.py: 0 = plain (class+op+args, the ONLY form C builds,
 * srmech_compose.c:299-303), 1 = map (map_over+body), 2 = fold
 * (fold_class+fold_op+fold_init+over), 3 = unrecognised. */
static int a_step_form(const srmech_toml_value_t *s)
{
    assert(s != NULL);
    if (s->type != SRMECH_TOML_TABLE) { return 3; }
    assert(s->u.tbl.keys != NULL || s->u.tbl.n == 0u);
    if (tv_get(s, "map_over") != NULL || tv_get(s, "body") != NULL) { return 1; }
    if (tv_get(s, "fold_op") != NULL || tv_get(s, "fold_class") != NULL) { return 2; }
    if (tv_get(s, "class") != NULL && tv_get(s, "op") != NULL
        && tv_get(s, "args") != NULL) { return 0; }
    return 3;
}

/* Count reference namespaces the C parse gate does NOT know, by flat text scan
 * over the ALREADY-EMITTED chain JSON (sees every nesting depth, no stack). */
static int ns_unknown_count(const char *js, size_t n, char *out, size_t cap)
{
    size_t i;
    int bad = 0;
    assert(js != NULL);
    assert(out != NULL && cap > 8u);
    out[0] = '\0';
    for (i = 0u; i + 2u < n; i++) {
        size_t j, k;
        int known = 0;
        if (js[i] != '"' || js[i + 1] != '@') { continue; }
        j = i + 2u;
        while (j < n && js[j] != '.' && js[j] != '[' && js[j] != '"') { j++; }
        for (k = 0u; k < 4u; k++) {
            size_t l = strlen(C_REF_NS[k]);
            if (l == j - (i + 2u) && memcmp(js + i + 2u, C_REF_NS[k], l) == 0) {
                known = 1;
            }
        }
        if (known) { continue; }
        bad++;
        if (strlen(out) + (j - i) + 4u < cap) {
            size_t o = strlen(out);
            if (o > 0u) { out[o++] = '|'; }
            memcpy(out + o, js + i + 1u, j - (i + 1u));
            out[o + (j - (i + 1u))] = '\0';
        }
    }
    return bad;
}

/* Count FLOAT / BOOL scalars anywhere under `root`, iteratively (same explicit
 * frame stack as tj_emit; no recursion). These are the values the run loop's
 * arg marshaller cr_json_scalar (srmech_compose_run.c:207-220) DECLINES — it
 * accepts INT, NULL and STRING only. So this counter measures the SECOND wall,
 * the one the op-table gap currently masks: widening cr_dispatch's table alone
 * would still leave every chain with a float or bool argument declining. */
static void tv_count_fb(const srmech_toml_value_t *root, int *n_float,
                        int *n_bool)
{
    tj_frame_t st[TJ_MAX_DEPTH];
    int sp;
    assert(n_float != NULL && n_bool != NULL);
    assert(TJ_MAX_DEPTH > 2);
    *n_float = 0;
    *n_bool = 0;
    if (root == NULL) { return; }
    st[0].v = root;
    st[0].i = 0u;
    sp = 1;
    while (sp > 0) {
        tj_frame_t *f = &st[sp - 1];
        const srmech_toml_value_t *v = f->v;
        int is_arr = (v->type == SRMECH_TOML_ARRAY);
        uint32_t n;
        if (!is_arr && v->type != SRMECH_TOML_TABLE) {
            if (v->type == SRMECH_TOML_FLOAT) { (*n_float)++; }
            if (v->type == SRMECH_TOML_BOOL) { (*n_bool)++; }
            sp--;
            continue;
        }
        n = is_arr ? v->u.arr.n : v->u.tbl.n;
        if (f->i >= n) { sp--; continue; }
        st[sp].v = is_arr ? v->u.arr.items[f->i] : v->u.tbl.vals[f->i];
        f->i++;
        if (sp >= TJ_MAX_DEPTH - 1 || st[sp].v == NULL) { return; }
        st[sp].i = 0u;
        sp++;
    }
}

