/* Build the chain JSON exactly as srmech/dsl/_cascade_chain.py:118-127 builds
 * the dict it hands to compose.parse_chain_spec: the four keys name / summary /
 * returns / steps, with name = "<op>.<variant|default>" and summary falling
 * back to [cascade].purpose. Returns 0 = HOST_LIMIT (emit failed). */
static int a_chain_json(const char *op, const srmech_toml_value_t *casc,
                        const srmech_toml_value_t *entry, hb_t *o)
{
    const char *p = NULL;
    uint32_t n = 0u;
    const srmech_toml_value_t *steps;
    assert(op != NULL && casc != NULL);
    assert(entry != NULL && o != NULL);
    steps = tv_get(entry, "steps");
    if (steps == NULL) { return 0; }
    hb_raw(o, "{\"name\":", 8u);
    hb_ch(o, '"');
    hb_raw(o, op, strlen(op));
    hb_ch(o, '.');
    if (tv_str(entry, "variant", &p, &n)) { hb_raw(o, p, n); }
    else { hb_raw(o, "default", 7u); }
    hb_ch(o, '"');
    hb_raw(o, ",\"summary\":", 11u);
    if (tv_str(entry, "summary", &p, &n) || tv_str(casc, "purpose", &p, &n)) {
        hb_jstr(o, p, n);
    } else {
        hb_jstr(o, op, strlen(op));
    }
    hb_raw(o, ",\"returns\":", 11u);
    if (tv_str(entry, "returns", &p, &n)) { hb_jstr(o, p, n); }
    else { hb_jstr(o, "", 0u); }
    hb_raw(o, ",\"steps\":", 9u);
    if (!tj_emit(steps, o)) { return 0; }
    hb_ch(o, '}');
    return o->failed ? 0 : 1;
}

/* ctx = {"row": null, "inputs": <proof_cases[0].inputs>} — the shape
 * compose.run_chain(spec, inputs=bound) builds. */
static int a_ctx_json(const srmech_toml_value_t *entry, hb_t *o)
{
    uint32_t np = 0u;
    const srmech_toml_value_t *pc0, *ins;
    assert(entry != NULL);
    assert(o != NULL);
    hb_raw(o, "{\"row\":null,\"inputs\":", 21u);
    pc0 = tv_entry(tv_get(entry, "proof_cases"), 0u, &np);
    ins = (pc0 != NULL) ? tv_get(pc0, "inputs") : NULL;
    if (ins == NULL) { hb_raw(o, "{}", 2u); }
    else if (!tj_emit(ins, o)) { return 0; }
    hb_ch(o, '}');
    return o->failed ? 0 : 1;
}

/* Per-chain static blocker census (what the C gates will refuse, and why),
 * written into g_blk. Purely predictive; the verdict is the measured rc. */
static void a_blockers(const srmech_toml_value_t *entry, const char *js,
                       size_t jsn, int *n_map, int *n_fold, int *n_offtab)
{
    uint32_t i, ns = 0u;
    const srmech_toml_value_t *steps;
    assert(entry != NULL && js != NULL);
    assert(n_map != NULL && n_fold != NULL && n_offtab != NULL);
    *n_map = 0; *n_fold = 0; *n_offtab = 0;
    steps = tv_get(entry, "steps");
    (void)tv_entry(steps, 0u, &ns);
    for (i = 0u; i < ns; i++) {
        uint32_t dummy = 0u;
        const srmech_toml_value_t *s = tv_entry(steps, i, &dummy);
        const char *op = NULL;
        uint32_t opl = 0u;
        int form;
        if (s == NULL) { continue; }
        form = a_step_form(s);
        if (form == 1) { (*n_map)++; }
        if (form == 2) { (*n_fold)++; }
        if (form == 0 && tv_str(s, "op", &op, &opl)
            && !op_in_c_table(op, opl)) { (*n_offtab)++; }
    }
    (void)ns_unknown_count(js, jsn, g_blk, sizeof(g_blk));
}

/* Fill pred[6] = {map_steps, fold_steps, ops_off_table, unknown_ns,
 * float_args, bool_args} for one chain entry. Split out of a_run_variant for
 * JPL Rule 4. The float/bool census covers ONLY what the run loop actually
 * marshals — the step declarations (literal args + map bodies) plus the ONE
 * proof case this host binds as ctx. Counting the whole chain entry would fold
 * in every other proof case, and the field name would then overstate it. */
static void a_predict(const srmech_toml_value_t *entry, const char *js,
                      size_t jsn, int *pred)
{
    int f2 = 0, b2 = 0;
    uint32_t np = 0u;
    const srmech_toml_value_t *pc0;
    assert(entry != NULL && js != NULL);
    assert(pred != NULL);
    pred[3] = ns_unknown_count(js, jsn, g_blk, sizeof(g_blk));
    a_blockers(entry, js, jsn, &pred[0], &pred[1], &pred[2]);
    pc0 = tv_entry(tv_get(entry, "proof_cases"), 0u, &np);
    tv_count_fb(tv_get(entry, "steps"), &pred[4], &pred[5]);
    tv_count_fb((pc0 != NULL) ? tv_get(pc0, "inputs") : NULL, &f2, &b2);
    pred[4] += f2;
    pred[5] += b2;
}

/* Emit one surface-A NDJSON record. Split out of a_run_variant purely to hold
 * both functions under the 60-line JPL Rule 4 bound. Reads g_sha / g_blk /
 * g_out, which a_run_variant has just filled. */
static void a_emit(const char *op, const hb_t *cj, const hb_t *cx,
                   srmech_status_t rp, srmech_status_t rr,
                   const int *pred, size_t need_s, size_t need_r)
{
    assert(op != NULL && pred != NULL);
    assert(cj != NULL && cx != NULL);
    printf("{\"section\":\"A\",\"op\":\"%s\",\"chain_bytes\":%zu,"
           "\"ctx_bytes\":%zu,\"spec_parse_rc\":%d,\"spec_sha256\":\"%s\","
           "\"chain_run_rc\":%d,"
           "\"value\":%s,\"pred_map_steps\":%d,\"pred_fold_steps\":%d,"
           "\"pred_ops_off_table\":%d,\"pred_unknown_ns\":%d,"
           "\"pred_float_args\":%d,\"pred_bool_args\":%d,"
           "\"unknown_ns\":\"%s\",\"arena_spec_need\":%zu,"
           "\"arena_run_need\":%zu,\"verdict\":\"%s\"}\n",
           op, cj->len, cx->len, (int)rp, g_sha, (int)rr,
           (rr == SRMECH_OK) ? g_out : "null",
           pred[0], pred[1], pred[2], pred[3], pred[4], pred[5], g_blk,
           need_s, need_r,
           (rr == SRMECH_OK) ? "C_RAN" : "C_DECLINED");
}

/* Emit a HOST_LIMIT record — a refusal by THIS HOST, never by C. Kept distinct
 * from C_DECLINED so a harness shortfall can never be counted as a C gap. */
static void a_host_limit(const char *op, const char *why, size_t ns, size_t nr)
{
    assert(op != NULL);
    assert(why != NULL);
    printf("{\"section\":\"A\",\"op\":\"%s\",\"verdict\":\"HOST_LIMIT\","
           "\"why\":\"%s\",\"need_spec\":%zu,\"need_run\":%zu}\n",
           op, why, ns, nr);
}

/* Drive both surface-A entry points for ONE chain variant and emit its NDJSON
 * record. Returns 1 if the chain ran to a value in C. */
static int a_run_variant(const char *op, const srmech_toml_value_t *casc,
                         const srmech_toml_value_t *entry, host_tally_t *t)
{
    hb_t cj, cx;
    size_t need_s, need_r, ol = 0u;
    srmech_status_t rp, rr;
    /* pred[] = {map_steps, fold_steps, ops_off_table, unknown_ns,
     *           float_args, bool_args} — static predictions, measured after. */
    int pred[6] = {0, 0, 0, 0, 0, 0};
    assert(op != NULL && casc != NULL);
    assert(entry != NULL && t != NULL);
    hb_init(&cj, g_json, sizeof(g_json));
    hb_init(&cx, g_ctx, sizeof(g_ctx));
    t->a_chains++;
    if (!a_chain_json(op, casc, entry, &cj) || !a_ctx_json(entry, &cx)) {
        t->a_host_limit++;
        a_host_limit(op, "chain or ctx emit failed", 0u, 0u);
        return 0;
    }
    a_predict(entry, cj.p, cj.len, pred);
    need_s = srmech_chain_spec_parse_arena_bytes(cj.len);
    need_r = srmech_chain_run_arena_bytes(cj.len, cx.len);
    if (need_s > sizeof(g_aux_ws) || need_r > sizeof(g_run_ws)) {
        t->a_host_limit++;
        a_host_limit(op, "static arena short", need_s, need_r);
        return 0;
    }
    /* The C entry points write NO trailing NUL (documented contract), so the
     * host must terminate at *out_len before any %s use. Getting this wrong is
     * how the first run of this harness printed a stale tail.
     * The Class-A hash below content-addresses the NORMALIZED spec: it is the
     * cross-check that the host's TOML->JSON mirror is FAITHFUL for every
     * accepting chain, not just for the control. */
    rp = srmech_chain_spec_parse(cj.p, cj.len, g_aux_ws, sizeof(g_aux_ws),
                                 g_out, sizeof(g_out) - 1u, &ol);
    g_sha[0] = '\0';
    if (rp == SRMECH_OK) {
        t->a_spec_ok++;
        if (srmech_sha256_hex((const uint8_t *)g_out, ol, g_sha) != SRMECH_OK) {
            g_sha[0] = '\0';
        }
    } else {
        t->a_spec_rej++;
    }
    ol = 0u;
    rr = srmech_chain_run(cj.p, cj.len, cx.p, cx.len, g_run_ws,
                          sizeof(g_run_ws), g_out, sizeof(g_out) - 1u, &ol);
    g_out[(rr == SRMECH_OK && ol < sizeof(g_out)) ? ol : 0u] = '\0';
    a_emit(op, &cj, &cx, rp, rr, pred, need_s, need_r);
    if (rr == SRMECH_OK) { t->a_run_ok++; return 1; }
    t->a_run_rej++;
    /* A rejection with NO predicted cause is UNATTRIBUTED and must be reported
     * as such — an unattributed rejection is worse than none, because it
     * inflates the gap. Held at strict zero by the summary. */
    if (pred[0] == 0 && pred[1] == 0 && pred[2] == 0 && pred[3] == 0) {
        t->a_unattributed++;
    }
    return 0;
}

/* One descriptor file: parse it, walk every declared [[cascade.chain]]. */
static void a_descriptor(const char *dir, const char *fname, host_tally_t *t)
{
    char path[HOST_PATH_CAP];
    size_t n = 0u;
    srmech_toml_value_t *root = NULL;
    const srmech_toml_value_t *casc, *chain;
    const char *nm = NULL;
    uint32_t nl = 0u, nch = 0u, i;
    assert(dir != NULL && fname != NULL);
    assert(t != NULL);
    (void)snprintf(path, sizeof(path), "%.*s/%.*s",
                   (int)(HOST_PATH_CAP / 2u), dir,
                   (int)(HOST_NAME_CAP - 1u), fname);
    if (slurp(path, g_src, sizeof(g_src), &n) != SRMECH_OK) { return; }
    if (srmech_toml_parse(g_src, n, g_toml_ws, sizeof(g_toml_ws),
                          &root) != SRMECH_OK) {
        printf("{\"section\":\"A\",\"file\":\"%s\",\"verdict\":\"HOST_LIMIT\","
               "\"why\":\"srmech_toml_parse declined\"}\n", fname);
        t->a_host_limit++;
        return;
    }
    t->a_descriptors++;
    casc = tv_get(root, "cascade");
    if (!tv_str(casc, "name", &nm, &nl)) { return; }
    chain = tv_get(casc, "chain");
    (void)tv_entry(chain, 0u, &nch);
    if (nch == 0u) {
        t->a_leaf++;
        printf("{\"section\":\"A\",\"op\":\"%.*s\",\"verdict\":\"LEAF\"}\n",
               (int)nl, nm);
        return;
    }
    for (i = 0u; i < nch; i++) {
        uint32_t d = 0u;
        const srmech_toml_value_t *e = tv_entry(chain, i, &d);
        char opname[HOST_NAME_CAP];
        (void)snprintf(opname, sizeof(opname), "%.*s", (int)nl, nm);
        if (e != NULL) { (void)a_run_variant(opname, casc, e, t); }
    }
}

