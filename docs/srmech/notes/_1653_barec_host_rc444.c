typedef struct row_pick {
    const char *want;
    int         found;
} row_pick_t;

/* srmech_ndjson_iter callback: keep the FIRST data row whose chain_id matches.
 * '#' comment lines are the descriptor's own convention, not NDJSON's. */
static srmech_status_t b_row_cb(const char *line, size_t len, size_t lineno,
                                void *user)
{
    row_pick_t *pk = (row_pick_t *)user;
    const srmech_json_value_t *r;
    const char *cid = NULL;
    uint32_t cl = 0u;
    assert(line != NULL || len == 0u);
    assert(user != NULL);
    (void)lineno;
    if (pk->found || len == 0u || line[0] == '#' || len + 2u >= sizeof(g_row)) {
        return SRMECH_OK;
    }
    r = j_parse(line, len, g_aux_ws, sizeof(g_aux_ws));
    if (!j_str(r, "chain_id", &cid, &cl)) { return SRMECH_OK; }
    if (strlen(pk->want) != (size_t)cl
        || memcmp(cid, pk->want, (size_t)cl) != 0) { return SRMECH_OK; }
    memcpy(g_row, line, len);
    g_row[len] = '\0';
    pk->found = 1;
    return SRMECH_OK;
}

/* Compare the C value descriptor against the row's OWN attested expectation.
 * "s" -> expected_pi_string; "q" -> expected_num / expected_den. Returns 1 on
 * byte/value parity, 0 otherwise, -1 if the row declares no expectation. */
static int b_parity(const char *desc, size_t dn, const char *row, size_t rn)
{
    const srmech_json_value_t *d, *r, *m;
    const char *k = NULL, *v = NULL;
    uint32_t kl = 0u, vl = 0u;
    assert(desc != NULL && row != NULL);
    assert(dn > 0u && rn > 0u);
    d = j_parse(desc, dn, g_aux_ws, sizeof(g_aux_ws));
    r = j_parse(row, rn, g_aux_ws + sizeof(g_aux_ws) / 2u,
                sizeof(g_aux_ws) / 2u);
    if (d == NULL || r == NULL || !j_str(d, "k", &k, &kl)) { return 0; }
    if (kl == 1u && k[0] == 's' && j_str(d, "v", &v, &vl)) {
        const char *e = NULL;
        uint32_t el = 0u;
        if (!j_str(r, "expected_pi_string", &e, &el)) { return -1; }
        return (el == vl && memcmp(e, v, vl) == 0) ? 1 : 0;
    }
    if (kl == 1u && k[0] == 'q' && j_str(d, "n", &v, &vl)) {
        long long gn = strtoll(v, NULL, 10), gd = 0;
        if (!j_str(d, "d", &v, &vl)) { return 0; }
        gd = strtoll(v, NULL, 10);
        m = srmech_json_object_get(r, "expected_num");
        if (m == NULL || m->type != SRMECH_JSON_INT) { return -1; }
        if (m->u.i != gn) { return 0; }
        m = srmech_json_object_get(r, "expected_den");
        if (m == NULL || m->type != SRMECH_JSON_INT) { return -1; }
        return (m->u.i == gd) ? 1 : 0;
    }
    return -1;
}

/* Emit one surface-B NDJSON record (split out for JPL Rule 4). */
static void b_emit(const char *chain_name, size_t cjl, size_t cxl,
                   srmech_status_t rp, srmech_status_t rr, int par, size_t need)
{
    assert(chain_name != NULL);
    assert(chain_name[0] != '\0');
    printf("{\"section\":\"B\",\"chain\":\"%s\",\"catalog_bytes\":%zu,"
           "\"ctx_bytes\":%zu,\"catalog_parse_rc\":%d,\"catalog_run_rc\":%d,"
           "\"value\":%s,\"attested_parity\":%d,\"arena_run_need\":%zu,"
           "\"verdict\":\"%s\"}\n",
           chain_name, cjl, cxl, (int)rp, (int)rr,
           (rr == SRMECH_OK) ? g_out : "null", par, need,
           (rr == SRMECH_OK && par == 1) ? "C_RAN_PARITY_OK"
                                         : (rr == SRMECH_OK ? "C_RAN"
                                                            : "C_DECLINED"));
}

/* One surface-B target: a shipped AMSC descriptor + one of its declared
 * `[[catalog.operator_chain]]` names + its shipped attested NDJSON. */
static void b_target(const char *dir, const char *chain_name,
                     host_tally_t *t)
{
    char path[HOST_PATH_CAP];
    hb_t cj, cx;
    size_t n = 0u, ol = 0u, need;
    srmech_toml_value_t *root = NULL;
    row_pick_t pk;
    srmech_status_t rp, rr;
    int par = -1;
    assert(dir != NULL && chain_name != NULL);
    assert(t != NULL);
    t->b_targets++;
    hb_init(&cj, g_json, sizeof(g_json));
    hb_init(&cx, g_ctx, sizeof(g_ctx));
    (void)snprintf(path, sizeof(path), "%s/descriptor.toml", dir);
    if (slurp(path, g_src, sizeof(g_src), &n) != SRMECH_OK
        || srmech_toml_parse(g_src, n, g_toml_ws, sizeof(g_toml_ws),
                             &root) != SRMECH_OK
        || !tj_emit(tv_get(root, "catalog"), &cj)) {
        t->b_host_limit++;
        printf("{\"section\":\"B\",\"chain\":\"%s\",\"verdict\":\"HOST_LIMIT\","
               "\"why\":\"descriptor read/parse/emit failed\"}\n", chain_name);
        return;
    }
    pk.want = chain_name;
    pk.found = 0;
    (void)snprintf(path, sizeof(path), "%s/row.ndjson", dir);
    if (srmech_ndjson_iter(path, b_row_cb, &pk) != SRMECH_OK || !pk.found) {
        t->b_host_limit++;
        printf("{\"section\":\"B\",\"chain\":\"%s\",\"verdict\":\"HOST_LIMIT\","
               "\"why\":\"no attested row for this chain_id\"}\n", chain_name);
        return;
    }
    /* ctx = {"row": <the attested NDJSON row VERBATIM>, "inputs": {}} — the row
     * line is already valid JSON, so no re-encoding step can corrupt it. */
    hb_raw(&cx, "{\"row\":", 7u);
    hb_raw(&cx, g_row, strlen(g_row));
    hb_raw(&cx, ",\"inputs\":{}}", 13u);
    need = srmech_catalog_run_chain_arena_bytes(cj.len, cx.len);
    rp = srmech_chain_catalog_parse(cj.p, cj.len, g_aux_ws, sizeof(g_aux_ws),
                                    g_out, sizeof(g_out) - 1u, &ol);
    if (rp == SRMECH_OK) { t->b_parse_ok++; }
    ol = 0u;
    rr = (need > sizeof(g_run_ws)) ? SRMECH_ERR_OVERFLOW
       : srmech_catalog_run_chain(cj.p, cj.len, chain_name, strlen(chain_name),
                                  cx.p, cx.len, g_run_ws, sizeof(g_run_ws),
                                  g_out, sizeof(g_out) - 1u, &ol);
    g_out[(rr == SRMECH_OK && ol < sizeof(g_out)) ? ol : 0u] = '\0';
    if (rr == SRMECH_OK) {
        t->b_run_ok++;
        par = b_parity(g_out, ol, g_row, strlen(g_row));
        if (par == 1) { t->b_parity_ok++; }
    }
    b_emit(chain_name, cj.len, cx.len, rp, rr, par, need);
}

/* ----------------------------------------------------------------------
 * Section [0] — the POSITIVE CONTROL through the surface-A code path.
 * ---------------------------------------------------------------------- */

static int host_control(host_tally_t *t)
{
    srmech_toml_value_t *root = NULL;
    const srmech_toml_value_t *casc, *e;
    host_tally_t ct;                 /* the control's OWN counters, so it can
                                      * never inflate the shipped census */
    uint32_t nch = 0u;
    int ran;
    assert(t != NULL);
    assert(sizeof(g_control_toml) > 64u);
    memset(&ct, 0, sizeof(ct));
    t->controls_run++;
    if (srmech_toml_parse(g_control_toml, sizeof(g_control_toml) - 1u,
                          g_toml_ws, sizeof(g_toml_ws), &root) != SRMECH_OK) {
        printf("{\"section\":\"0\",\"control\":\"toml_parse\","
               "\"verdict\":\"CONTROL_FAILED\"}\n");
        return 0;
    }
    casc = tv_get(root, "cascade");
    e = tv_entry(tv_get(casc, "chain"), 0u, &nch);
    if (e == NULL) {
        printf("{\"section\":\"0\",\"control\":\"chain_lookup\","
               "\"verdict\":\"CONTROL_FAILED\"}\n");
        return 0;
    }
    ran = a_run_variant("hostctl", casc, e, &ct);
    /* The control's own value must be the exact rational 5/6. The separators
     * are canonical json.dumps's ": " / ", " — NOT the compact spelling. */
    if (ran && strstr(g_out, "\"k\": \"q\"") != NULL
        && strstr(g_out, "\"n\": \"5\"") != NULL
        && strstr(g_out, "\"d\": \"6\"") != NULL) {
        t->controls_ok++;
        printf("{\"section\":\"0\",\"control\":\"rational_add\","
               "\"value\":%s,\"verdict\":\"CONTROL_OK\"}\n", g_out);
        return 1;
    }
    printf("{\"section\":\"0\",\"control\":\"rational_add\","
           "\"verdict\":\"CONTROL_FAILED\"}\n");
    return 0;
}

