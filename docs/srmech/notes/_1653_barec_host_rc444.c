/* ----------------------------------------------------------------------
 * Directory enumeration (deterministic order; no magic filename list).
 * ---------------------------------------------------------------------- */

static uint32_t list_tomls(const char *dir)
{
    DIR *d;
    struct dirent *de;
    uint32_t n = 0u, i, j;
    assert(dir != NULL);
    assert(HOST_MAX_FILES > 1u);
    d = opendir(dir);
    if (d == NULL) { return 0u; }
    while ((de = readdir(d)) != NULL && n < HOST_MAX_FILES) {
        size_t l = strlen(de->d_name);
        if (l < 6u || l >= HOST_NAME_CAP) { continue; }
        if (memcmp(de->d_name + l - 5u, ".toml", 5u) != 0) { continue; }
        memcpy(g_names[n], de->d_name, l + 1u);
        n++;
    }
    (void)closedir(d);
    for (i = 1u; i < n; i++) {              /* insertion sort: stable order */
        char key[HOST_NAME_CAP];
        memcpy(key, g_names[i], HOST_NAME_CAP);
        j = i;
        while (j > 0u && strcmp(g_names[j - 1u], key) > 0) {
            memcpy(g_names[j], g_names[j - 1u], HOST_NAME_CAP);
            j--;
        }
        memcpy(g_names[j], key, HOST_NAME_CAP);
    }
    return n;
}

