def bind_positional(real, a, kw):
    sig = inspect.signature(real)
    b = sig.bind(*a, **kw)
    b.apply_defaults()
    names = [n for n in sig.parameters
             if sig.parameters[n].kind not in
             (sig.parameters[n].VAR_POSITIONAL, sig.parameters[n].VAR_KEYWORD)]
    return names, [b.arguments[n] for n in names]


def orbit(real, seeds, base, slot):
    """S = the closure of the recorded SEEDS under f, varying ONE slot.

    This is rc427's stated criterion with the WINDOW removed: S is generated by
    f itself, so there is no modulus-smaller-than-the-carrier to get wrong.

      * f total on S      -- an IMAGE that raises collapses the closure to
                             NOT_TOTAL; a SEED that raises is simply dropped
                             (it was valid in another binding, not this one);
      * f(S) subset-of S  -- by construction;
      * non-injective     -- |f(S)| < |S|.

    |S| < 2 is VACUOUS, never GROUP: a lone fixed point makes every op with any
    fixed point a "bijection" and the test would stop separating.
    """
    x0 = base[slot]
    if ident(x0) is None:
        return {"verdict": "UNKEYABLE_SEED"}
    keys, img, dropped_seeds = set(), {}, 0
    pend = [(s, True) for s in seeds] or [(x0, True)]
    while pend:
        x, is_seed = pend.pop()
        kx = ident(x)
        if kx is None:
            return {"verdict": "UNKEYABLE_IMAGE", "set_size": len(keys)}
        if kx in keys:
            continue
        if type(x) is not type(x0):
            if is_seed:
                dropped_seeds += 1
                continue
            return {"verdict": "NOT_ENDO", "in_type": type(x0).__name__,
                    "out_type": type(x).__name__}
        args = list(base)
        args[slot] = x
        try:
            y = real(*args)
        except BaseException as exc:
            if is_seed:
                dropped_seeds += 1
                continue
            return {"verdict": "NOT_TOTAL", "exc": type(exc).__name__,
                    "msg": str(exc)[:180], "set_size": len(keys)}
        if type(y) is not type(x0):
            return {"verdict": "NOT_ENDO", "in_type": type(x0).__name__,
                    "out_type": type(y).__name__}
        ky = ident(y)
        if ky is None:
            return {"verdict": "UNKEYABLE_IMAGE", "set_size": len(keys)}
        keys.add(kx)
        img[kx] = ky
        pend.append((y, False))
        if len(keys) > MAX_SET:
            return {"verdict": "ORBIT_UNCLOSED", "set_size": len(keys),
                    "max_set": MAX_SET}
    n, m = len(keys), len(set(img.values()))
    if n < 2:
        return {"verdict": "VACUOUS", "set_size": n, "image_size": m,
                "why": "|S| < 2 -- a lone fixed point is not a measurement"}
    return {"verdict": "SEMIGROUP" if m < n else "GROUP",
            "set_size": n, "image_size": m, "dropped_seeds": dropped_seeds,
            "surviving": str(m) + "/" + str(n)}


def run_one(name):
    entry = BY_NAME.get(name)
    out = {"op": name}
    if entry is None:
        out["oracle"] = "ABSENT_FROM_REGISTRY"
        return out
    mod_name, _, fname = name.rpartition(".")
    fn_mod = importlib.import_module(mod_name)
    real = getattr(fn_mod, fname)
    calls, err = record_calls(entry, fn_mod, fname)
    out["snippet_error"] = err
    if not calls:
        out["oracle"] = "NO_VALID_ARG_RECOVERED"
        return out
    try:
        names, base = bind_positional(real, *calls[0])
    except BaseException as exc:
        out["oracle"] = "BIND_FAILED"
        out["bind_exc"] = type(exc).__name__ + ": " + str(exc)[:160]
        return out
    sig = inspect.signature(real)
    req = [n for n in names if sig.parameters[n].default is sig.parameters[n].empty]
    out["oracle"] = "ARG_RECOVERED"
    out["n_recorded_calls"] = len(calls)
    out["param_names"] = names
    out["required"] = req
    out["arg_types"] = [type(v).__name__ for v in base]
    out["arg_reprs"] = [repr(v)[:90] for v in base]
    # Every recorded call is a VALID call, so every value it put in this slot is
    # a valid value for it, and a collision between two distinct seeds is an
    # information-destruction witness a single orbit cannot see.
    #
    # BUT seeds are admitted ONLY from calls whose OTHER slots match `base`
    # exactly. Pooling across bindings re-imports the precise defect that
    # refuted instrument v1: the first draft of this instrument scored
    # ``mod_mul`` SEMIGROUP 222/223 on binding (b=96, n=223) because a seed
    # ``a=235`` harvested from a DIFFERENT published call collided with
    # ``235 mod 223 = 12``. That collapse is real for the map ``a -> 96a mod
    # 223`` on all of Z-nonneg, but it is once again the CROSS-BINDING window
    # talking, not the op on the binding under test. Same-binding only, and
    # ``mod_mul`` returns GROUP -- which is correct, gcd(96, 223) = 1.
    # For Tier A (one required param) there are no other slots, so this
    # restriction costs the headline class nothing.
    bound = []
    for a, kw in calls:
        try:
            bound.append(bind_positional(real, a, kw)[1])
        except BaseException:
            continue
    base_keys = [ident(v) for v in base]
    results = []
    for rn in req:
        slot = names.index(rn)
        seeds, seen_k, cross = [], set(), 0
        for b in bound:
            if slot >= len(b):
                continue
            same = all(ident(b[j]) == base_keys[j]
                       for j in range(min(len(b), len(base))) if j != slot)
            if not same:
                cross += 1
                continue
            k = ident(b[slot])
            if k is not None and k not in seen_k:
                seen_k.add(k)
                seeds.append(b[slot])
        r = orbit(real, seeds, base, slot)
        r["slot"] = rn
        r["n_seeds"] = len(seeds)
        r["cross_binding_seeds_rejected"] = cross
        results.append(r)
    out["slots"] = results
    order = ("SEMIGROUP", "GROUP", "NOT_ENDO", "ORBIT_UNCLOSED", "VACUOUS",
             "NOT_TOTAL", "UNKEYABLE_SEED", "UNKEYABLE_IMAGE")
    verds = [r["verdict"] for r in results]
    for v in order:
        if v in verds:
            out["verdict"] = v
            break
    else:
        out["verdict"] = "NONE"
    return out


