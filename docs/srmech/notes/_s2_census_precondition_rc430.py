def classify_exceptions(pairs):
    """pairs: list of (exc_type_name, message). Returns a WHY_BUCKETS member."""
    if not pairs:
        return "X_UNCLASSIFIED"
    kinds = {k for k, _ in pairs}
    if kinds & set(ENV_EXCS):
        return "X_ENV"
    for k, m in pairs:
        low = m.lower()
        if k in VALUE_EXCS and any(s in low for s in SHAPE_MARKERS):
            return "X_SHAPE_GUARD"
    for k, m in pairs:
        low = m.lower()
        if k in VALUE_EXCS and any(s in low for s in VALUE_MARKERS):
            return "X_VALUE_GUARD"
    for k, m in pairs:
        low = m.lower()
        if k in TYPE_EXCS and any(s in low for s in SHAPE_MARKERS):
            return "X_SHAPE_GUARD"
    if kinds & set(VALUE_EXCS):
        return "X_VALUE_GUARD"
    if kinds & set(TYPE_EXCS):
        return "X_TYPE_WALL"
    return "X_UNCLASSIFIED"


