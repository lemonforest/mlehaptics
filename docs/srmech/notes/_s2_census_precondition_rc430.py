class Worker:
    """A long-lived child the parent can kill. Nothing in-process can interrupt
    arbitrary Python reliably; a process kill cannot be defeated by a C loop."""

    def __init__(self, src_path, env):
        self.src_path = src_path
        self.env = env
        self.proc = None
        self.q = None
        self._start()

    def _start(self):
        self.proc = subprocess.Popen(
            [sys.executable, "-u", self.src_path],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, env=self.env,
        )
        self.q = []
        self.lock = threading.Lock()
        self.reader = threading.Thread(target=self._read, daemon=True)
        self.reader.start()

    def _read(self):
        proc = self.proc
        for line in proc.stdout:
            if line.startswith("\x01"):
                with self.lock:
                    self.q.append(line[1:])

    def kill(self):
        try:
            self.proc.kill()
        except Exception:
            pass

    def ask(self, name, budget):
        try:
            self.proc.stdin.write(name + "\n")
            self.proc.stdin.flush()
        except Exception:
            self.kill()
            self._start()
            return {"op": name, "oracle": "WORKER_RESTART"}
        t0 = time.monotonic()
        while time.monotonic() - t0 < budget:
            with self.lock:
                if self.q:
                    return json.loads(self.q.pop(0))
            if self.proc.poll() is not None:
                self.kill()
                self._start()
                return {"op": name, "oracle": "WORKER_DIED"}
            time.sleep(0.01)
        self.kill()
        self._start()
        return {"op": name, "oracle": "TIMEOUT", "budget_s": budget}


