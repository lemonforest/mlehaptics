def _fnode(fn):
    import ast as _ast
    import textwrap as _tw
    try:
        tree = _ast.parse(_tw.dedent(inspect.getsource(fn)))
    except (OSError, TypeError, SyntaxError, IndentationError):
        return None
    for n in tree.body:
        if isinstance(n, (_ast.FunctionDef, _ast.AsyncFunctionDef)):
            return n
    return None


def _atoms(test):
    """Split a boolean guard into ATOMS.

    ``a < 0 or b < 0`` names two parameters but is TWO INDEPENDENT single-param
    constraints, not a relation between a and b. Counting it as relational would
    inflate the one number this rc turns on, so the split is not optional.
    """
    import ast as _ast
    out = []

    def rec(n):
        if isinstance(n, _ast.BoolOp):
            for v in n.values:
                rec(v)
        elif isinstance(n, _ast.UnaryOp) and isinstance(n.op, _ast.Not):
            rec(n.operand)
        else:
            out.append(n)

    rec(test)
    return out


def _is_type_atom(a):
    """``isinstance(x, int)`` re-states the type the registry ALREADY publishes.
    Extracting it adds no information, so it is not a domain constraint."""
    import ast as _ast
    for c in _ast.walk(a):
        if isinstance(c, _ast.Call) and isinstance(c.func, _ast.Name) and \
                c.func.id in ("isinstance", "issubclass", "callable", "type"):
            return True
    return False


def _own_guard_atoms(fn, pset):
    import ast as _ast
    node = _fnode(fn)
    if node is None:
        return []
    rows = []
    for n in _ast.walk(node):
        test = None
        if isinstance(n, _ast.If) and any(isinstance(s, _ast.Raise) for s in n.body):
            test = n.test
        elif isinstance(n, _ast.Assert):
            test = n.test
        if test is None:
            continue
        for at in _atoms(test):
            names = sorted({x.id for x in _ast.walk(at)
                            if isinstance(x, _ast.Name) and x.id in pset})
            if names:
                rows.append({"params": names,
                             "kind": "TYPE" if _is_type_atom(at) else "DOMAIN",
                             "src": _ast.unparse(at)[:130]})
    return rows


def _callees(fn, live):
    """Direct callees this function forwards its LIVE names to, with the
    callee-param -> live-name map. The map is CARRIED down the chain: matching
    by bare name across scopes is unsound and manufactured a false positive
    (``group_algebra_table`` inheriting ``mod_add``'s ``n == 0``)."""
    import ast as _ast
    import types as _types
    node = _fnode(fn)
    if node is None:
        return []
    g = getattr(fn, "__globals__", {})
    out = []
    for n in _ast.walk(node):
        if not isinstance(n, _ast.Call):
            continue
        f = n.func
        if isinstance(f, _ast.Name):
            tgt = g.get(f.id)
        elif isinstance(f, _ast.Attribute) and isinstance(f.value, _ast.Name):
            base = g.get(f.value.id)
            tgt = getattr(base, f.attr, None) if base is not None else None
        else:
            continue
        if not isinstance(tgt, _types.FunctionType):
            continue
        tn = _fnode(tgt)
        if tn is None:
            continue
        ta = tn.args
        tps = [p.arg for p in
               (list(ta.posonlyargs) + list(ta.args) + list(ta.kwonlyargs))]
        m = {}
        for i, arg in enumerate(n.args):
            if isinstance(arg, _ast.Name) and arg.id in live and i < len(tps):
                m[tps[i]] = live[arg.id]
        for kw in n.keywords:
            if kw.arg and isinstance(kw.value, _ast.Name) and kw.value.id in live:
                m[kw.arg] = live[kw.value.id]
        if m:
            out.append((tgt, m))
    return out


def guard_profile(fn):
    """Guard atoms attributable to this op's OWN parameters, following
    delegation up to GUARD_DEPTH with a soundly-carried parameter map."""
    node = _fnode(fn)
    if node is None:
        return None
    a = node.args
    pos = list(a.posonlyargs) + list(a.args)
    ndef = len(a.defaults)
    req = [p.arg for p in (pos[:len(pos) - ndef] if ndef else pos)]
    req += [k.arg for k, d in zip(a.kwonlyargs, a.kw_defaults) if d is None]
    params = [p.arg for p in pos + list(a.kwonlyargs)]
    rows = _own_guard_atoms(fn, set(params))
    own = len(rows)
    seen = {fn}
    frontier = [(fn, {p: p for p in params}, 0)]
    while frontier:
        cur, live, d = frontier.pop()
        if d >= GUARD_DEPTH:
            continue
        for tgt, m in _callees(cur, live):
            if tgt in seen:
                continue
            seen.add(tgt)
            for r in _own_guard_atoms(tgt, set(m)):
                mapped = sorted({m[p] for p in r["params"] if p in m})
                if mapped:
                    rows.append({"params": mapped, "kind": r["kind"],
                                 "src": r["src"], "depth": d + 1,
                                 "via": tgt.__module__ + "." + tgt.__name__})
            frontier.append((tgt, m, d + 1))
    dom = [r for r in rows if r["kind"] == "DOMAIN"]
    if not dom:
        cls = "NO_DOMAIN_GUARD" if not rows else "TYPE_GUARD_ONLY"
    elif any(len(r["params"]) >= 2 for r in dom):
        cls = "DOMAIN_RELATIONAL"
    else:
        cls = "DOMAIN_SINGLE_PARAM"
    return {"params": params, "required": req, "atoms": rows,
            "own_atom_count": own, "class": cls}


