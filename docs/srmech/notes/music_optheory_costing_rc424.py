# §1  p-LIMIT / JUST INTONATION  —  Class J ∘ Class N
#
# CANDIDATE OP:  just_limit(num, den) -> dict
#   p-limit tuning IS exactly the multiplicative subgroup of ℚ⁺ generated by
#   the primes ≤ p (Wright, *Mathematics and Music*, AMS 2009, p.137). So the
#   op is: factor the numerator (Class J), factor the denominator (Class J),
#   union the prime supports, return the max. Exact, closed-form, total.
# ═════════════════════════════════════════════════════════════════════════════
def proto_just_limit(num, den):
    """PROTOTYPE — the p-limit of a ratio, through the shipped Class-J factor."""
    g = gcd(num, den)                       # Class I — reduce first
    num, den = num // g, den // g
    fn, fd = factor(num), factor(den)       # Class J — the prime supports
    primes = sorted({p for (p, _) in fn} | {p for (p, _) in fd})
    monzo = {}                              # the exponent vector (the "monzo")
    for (p, e) in fn:
        monzo[p] = monzo.get(p, 0) + e
    for (p, e) in fd:
        monzo[p] = monzo.get(p, 0) - e
    return {
        "ratio": f"{num}/{den}",
        "primes": primes,
        "limit": (max(primes) if primes else 1),
        "monzo": {str(p): monzo[p] for p in sorted(monzo)},
        "odd_limit": max([p for p in primes if p != 2] or [1]),
    }


