def pcs_transpose(s, n):
    return frozenset(cyclic_mod_add(x, n, 12) for x in s)


def pcs_invert(s):
    # inversion about 0: x -> -x mod 12, via the shipped modular add
    return frozenset(cyclic_mod_add(0, (12 - x) % 12, 12) for x in s)


def interval_vector(s):
    """The interval-class vector: how a set relates to ITSELF at every ic."""
    v = [0] * 6
    for a, b in itertools.combinations(sorted(s), 2):
        d = (b - a) % 12
        ic = d if d <= 6 else 12 - d
        v[ic - 1] += 1
    return tuple(v)


def _rotations(s):
    srt = sorted(s)
    n = len(srt)
    return [tuple(srt[(i + k) % n] for k in range(n)) for i in range(n)]


def _spans(rot):
    a0 = rot[0]
    return [ (x - a0) % 12 for x in rot[1:] ]


def normal_order(s, convention):
    """Rahn: minimise (d_last, d_{last-1}, ..., d_1). Forte: (d_last, d_1, d_2, ...)."""
    best = None
    for rot in _rotations(s):
        d = _spans(rot)
        if not d:
            key = ()
        elif convention == "rahn":
            key = tuple([d[-1]] + list(reversed(d[:-1])))
        else:
            key = tuple([d[-1]] + d[:-1])
        if best is None or key < best[0] or (key == best[0] and rot < best[1]):
            best = (key, rot)
    return best[1]


def prime_form(s, convention):
    cands = []
    for t in (s, pcs_invert(s)):
        no = normal_order(t, convention)
        cands.append(tuple((x - no[0]) % 12 for x in no))
    return min(cands)


def section_pc_set_theory():
    # Enumerate all set classes (Tn/TnI equivalence) of cardinality 2..10.
    classes_rahn, classes_forte = {}, {}
    for card in range(2, 11):
        for s in itertools.combinations(range(12), card):
            fs = frozenset(s)
            pr = prime_form(fs, "rahn")
            pf = prime_form(fs, "forte")
            classes_rahn.setdefault(pr, set()).add(fs)
            classes_forte.setdefault(pf, set()).add(fs)
    # A set class is the orbit under Tn/TnI; count them per cardinality.
    per_card = {}
    for pr in classes_rahn:
        per_card[len(pr)] = per_card.get(len(pr), 0) + 1
    emit(
        "pcs_set_class_census",
        set_classes_by_cardinality=per_card,
        total_2_to_10=len(classes_rahn),
        note=("the standard count of set classes of cardinality 2..10 under "
              "Tn/TnI; cardinalities 0,1,11,12 are trivial and excluded"),
    )

    # Where do the two conventions disagree? Compare, orbit by orbit.
    disagree = []
    seen = set()
    for card in range(2, 11):
        for s in itertools.combinations(range(12), card):
            fs = frozenset(s)
            pr, pf = prime_form(fs, "rahn"), prime_form(fs, "forte")
            if pr != pf and (pr, pf) not in seen:
                seen.add((pr, pf))
                disagree.append({"rahn": list(pr), "forte": list(pf),
                                 "cardinality": card,
                                 "interval_vector": list(interval_vector(fs))})
    emit(
        "pcs_forte_vs_rahn",
        n_disagreeing_set_classes=len(disagree),
        disagreements=disagree,
        expected_from_literature=6,
        expected_names=["5-20", "6-Z29", "6-31", "7-Z18", "7-20", "8-26"],
        reproduces_literature_count=(len(disagree) == 6),
        note=("Forte (1973) packs from the left; Rahn (1980) packs from the "
              "right. The literature count of affected prime forms is 6 of "
              "208. If this run does not reproduce 6, the divergence is "
              "reported UNVERIFIED and the spec must name its convention "
              "explicitly rather than assume one."),
    )

    # Interval vector — the "classification that can say all the notes it is NOT".
    for name, s in [("major triad", {0, 4, 7}), ("minor triad", {0, 3, 7}),
                    ("diminished 7th", {0, 3, 6, 9}),
                    ("whole-tone", {0, 2, 4, 6, 8, 10}),
                    ("diatonic scale", {0, 2, 4, 5, 7, 9, 11}),
                    ("chromatic hexachord", {0, 1, 2, 3, 4, 5})]:
        emit("pcs_interval_vector", name=name, pcs=sorted(s),
             interval_vector=list(interval_vector(frozenset(s))),
             prime_form_rahn=list(prime_form(frozenset(s), "rahn")))

    # The Z-relation: distinct set classes sharing an interval vector — the
    # exact place where "characterise a thing by all it is NOT" is INCOMPLETE.
    by_iv = {}
    for pr, members in classes_rahn.items():
        iv = interval_vector(next(iter(members)))
        by_iv.setdefault(iv, set()).add(pr)
    z_pairs = {iv: sorted(v) for iv, v in by_iv.items() if len(v) > 1}
    emit(
        "pcs_z_relation",
        n_interval_vectors_shared_by_multiple_set_classes=len(z_pairs),
        examples=[{"interval_vector": list(iv),
                   "set_classes": [list(p) for p in ps]}
                  for iv, ps in sorted(z_pairs.items())[:8]],
        note=("THE LOAD-BEARING CAVEAT for the user's (c): the interval "
              "vector does NOT determine the set class. Z-related pairs share "
              "an interval vector and are genuinely different objects. So "
              "'a classification that can say all the other notes it is NOT' "
              "is a real and computable object, but it is NOT a complete "
              "invariant — it is a lossy one, and the loss is exactly the "
              "Z-relation."),
    )
    emit(
        "pcs_design_verdict",
        candidate="pitch_class_transpose / pitch_class_invert / interval_vector / prime_form",
        classes="I (ℤ/12 modular action) ∘ E (catalog / normal-form selection)",
        exact=True,
        closed_form=True,
        rosetta_bucket_forecast="composition_of_c",
        verdict=("ACCEPT interval_vector + transpose + invert. prime_form "
                 "ACCEPT ONLY IF it names its convention in the op name or a "
                 "required argument — shipping an unnamed prime_form would "
                 "silently pick a side in a live 50-year disagreement and "
                 "would be wrong for whichever community it did not pick."),
    )


