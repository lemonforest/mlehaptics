def continued_fraction(numerator: int, denominator: int, max_depth: int = 30) -> List[int]:
    """Standard CF expansion. Used for F_{n+1} / F_n.

    F_{n+1}/F_n CF is ALWAYS [1; 1, 1, 1, ..., 1, 2] (truncated phi CF).
    """
    cf = []
    num, den = numerator, denominator
    while den != 0 and len(cf) < max_depth:
        q = num // den
        cf.append(q)
        num, den = den, num - q * den
    return cf


def fibonacci_cf_convergents(n_terms: int = 20) -> Dict:
    """Compute CF of F_{n+1}/F_n for large n, confirm [1; 1, 1, 1, ...]
    pattern. The CF of phi = (1 + sqrt(5))/2 is [1; 1, 1, 1, ...] — every
    a_i = 1. Fibonacci convergents ARE this CF truncated.
    """
    fibs = fibonacci_sequence(n_terms + 2)
    # CF of F_{n+1} / F_n
    cfs = []
    for i in range(2, n_terms + 2):
        cf = continued_fraction(fibs[i], fibs[i - 1])
        cfs.append(cf)

    # Check the "all ones" property (except possibly last term)
    all_ones_count = 0
    for cf in cfs[-5:]:  # last 5
        if all(a == 1 for a in cf[:-1]) and cf[-1] in (1, 2):
            all_ones_count += 1

    # Recover phi from last convergent ratio
    last_ratio = fibs[-1] / fibs[-2] if fibs[-2] != 0 else float("nan")
    phi = (1 + math.sqrt(5)) / 2
    phi_err = abs(last_ratio - phi)

    return {
        "n_terms": n_terms,
        "fibs": fibs[:10] + ["..."] + fibs[-3:],
        "cf_of_last_ratio": cfs[-1],
        "all_ones_property_check": f"{all_ones_count}/5 last convergents have all-ones CF",
        "phi_recovered": float(last_ratio),
        "phi_canonical": float(phi),
        "abs_error": float(phi_err),
        "kepler_relevance": (
            "Fibonacci CF = phi-CF = [1;1,1,1,...] = SLOWEST CF convergence "
            "(phi is 'most irrational'). Kepler eps = 0.0167 has rapid CF "
            "convergence — these are at OPPOSITE ENDS of the Class N rate-of-approach "
            "spectrum."
        ),
    }


