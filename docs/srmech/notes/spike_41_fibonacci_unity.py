def normalised_power_spectrum(seq: np.ndarray, n_fft: int = 256) -> np.ndarray:
    """FFT-based normalised PSD."""
    seq = np.asarray(seq, dtype=np.float64)
    seq = seq - np.mean(seq)
    if np.all(seq == 0):
        return np.zeros(n_fft // 2)
    # Pad or truncate to n_fft
    if len(seq) >= n_fft:
        seq = seq[:n_fft]
    else:
        seq = np.concatenate([seq, np.zeros(n_fft - len(seq))])
    psd = np.abs(np.fft.rfft(seq)) ** 2
    psd = psd[1:]  # drop DC
    norm = np.linalg.norm(psd)
    return psd / norm if norm > 0 else psd


def cosine_sim(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    na = np.linalg.norm(a)
    nb = np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


