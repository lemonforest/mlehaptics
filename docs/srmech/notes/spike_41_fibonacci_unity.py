def pisano_period(m: int) -> int:
    """Pisano period pi(m): the period of F_n mod m.

    Examples: pi(2) = 3, pi(3) = 8, pi(5) = 20, pi(7) = 16, pi(11) = 10.
    """
    if m == 1:
        return 1
    a, b = 0, 1
    for k in range(1, 6 * m + 1):
        a, b = b, (a + b) % m
        if a == 0 and b == 1:
            return k
    return -1  # not found within bound


