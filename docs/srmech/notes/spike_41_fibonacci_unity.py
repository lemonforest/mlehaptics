def _find_period(seq: List[int], max_check: int = 100) -> int:
    """Find the period of a periodic integer sequence."""
    n = len(seq)
    if n < 4:
        return -1
    for period in range(1, min(max_check, n // 2)):
        if all(seq[i] == seq[i + period] for i in range(min(period * 3, n - period))):
            return period
    return -1


