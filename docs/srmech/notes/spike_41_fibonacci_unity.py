def asymptotic_approach(seq: List[float]) -> Dict:
    """Class K asymptotic-DOF signature: how does the sequence approach
    its limit?

    For Fibonacci ratios r_n = F_{n+1}/F_n, r_n -> phi. The approach is
    exponential (NOT power-law and NOT 1/n).

    For Kepler EOC partial sums, the convergence of the EOC series is
    geometric in eps.

    Asymptotic-DOF (per [[user_stance_asymptotic_dof_sidesteps_infinity]])
    parameterises the RATE of approach to the limit, not the limit's
    cardinality.
    """
    if len(seq) < 4:
        return {"error": "sequence too short"}
    # Fit log|r_n - r_inf| vs n. r_inf = last term.
    r_inf = seq[-1]
    residuals = np.array([abs(r - r_inf) for r in seq[:-2]], dtype=np.float64)
    nonzero = residuals > 0
    if nonzero.sum() < 4:
        return {"r_inf": float(r_inf), "approach_form": "degenerate"}
    log_res = np.log(residuals[nonzero])
    idx = np.arange(len(residuals))[nonzero]
    A = np.vstack([idx, np.ones_like(idx)]).T
    slope, intercept = np.linalg.lstsq(A, log_res, rcond=None)[0]

    # Geometric ratio per step
    ratio_per_step = math.exp(slope)

    return {
        "r_inf": float(r_inf),
        "approach_log_slope": float(slope),
        "approach_geom_ratio": float(ratio_per_step),
        "fit_form": "log|r_n - r_inf| = slope * n + const  (geometric / exponential approach)",
    }


