def fibonacci_sequence(n: int) -> List[int]:
    """Standard Fibonacci F_0 = 0, F_1 = 1, F_n = F_{n-1} + F_{n-2}."""
    seq = [0, 1]
    for _ in range(n - 2):
        seq.append(seq[-1] + seq[-2])
    return seq[:n]


