def equation_of_centre(epsilon: float, n_modes: int, n_samples: int = 4096) -> np.ndarray:
    """(C) Kepler equation-of-centre c_k = eps^k / k (Cauchy form).

    Build the longitude correction series:
      Delta(M) = 2 * sum_{k>=1} (1/k) * eps^k * sin(k*M)

    Per Brouwer & Clemence 1961 sec 3.2 (project-verified Spike #30B). The
    output is the time-series in mean-anomaly M; we'll Fourier-decompose it
    later to recover c_k. For direct c_k inspection, we just return the
    coefficients [eps, eps^2/2, eps^3/3, ..., eps^N / N].
    """
    coefficients = np.array(
        [epsilon ** k / k for k in range(1, n_modes + 1)], dtype=np.float64
    )
    return coefficients


