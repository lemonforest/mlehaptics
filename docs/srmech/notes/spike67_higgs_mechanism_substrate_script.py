# Standard Fano plane / octonion multiplication table.
# Index convention: e_0 = 1 (identity), e_1..e_7 imaginary units.
# Standard 7 Fano lines (associative triples) {i,j,k} with e_i e_j = e_k:
FANO_LINES = [
    (1, 2, 3),
    (1, 4, 5),
    (1, 7, 6),
    (2, 4, 6),
    (2, 5, 7),
    (3, 4, 7),
    (3, 6, 5),
]


def build_oct_table() -> Dict[Tuple[int, int], Tuple[int, int]]:
    """Return dict (i,j) -> (sign, k) for the octonion product e_i * e_j.

    Uses the standard cyclic orientation: each Fano line (a,b,c) implies
      e_a e_b = +e_c, e_b e_c = +e_a, e_c e_a = +e_b,
    with sign-reverse for the opposite order.
    e_i * e_i = -1 (encoded with k=0 sign -1).
    e_0 = 1 acts as identity.
    """
    table: Dict[Tuple[int, int], Tuple[int, int]] = {}
    # identity row/column
    for i in range(8):
        table[(0, i)] = (1, i)
        table[(i, 0)] = (1, i)
    # e_i * e_i = -1
    for i in range(1, 8):
        table[(i, i)] = (-1, 0)
    # Cyclic lines
    for a, b, c in FANO_LINES:
        # forward cycle
        table[(a, b)] = (1, c)
        table[(b, c)] = (1, a)
        table[(c, a)] = (1, b)
        # reverse cycle
        table[(b, a)] = (-1, c)
        table[(c, b)] = (-1, a)
        table[(a, c)] = (-1, b)
    return table


def oct_mul(x: List[float], y: List[float], table) -> List[float]:
    """Multiply two octonions x*y. x,y are 8-vectors over R."""
    out = [0.0] * 8
    for i in range(8):
        if x[i] == 0:
            continue
        for j in range(8):
            if y[j] == 0:
                continue
            sign, k = table[(i, j)]
            out[k] += sign * x[i] * y[j]
    return out


def assoc_residual(x, y, z, table) -> float:
    """|| (xy)z - x(yz) ||_inf — Class L cascade discrepancy."""
    left = oct_mul(oct_mul(x, y, table), z, table)
    right = oct_mul(x, oct_mul(y, z, table), table)
    return max(abs(l - r) for l, r in zip(left, right))


